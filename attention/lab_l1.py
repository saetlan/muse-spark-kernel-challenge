import statistics as _st
import time as _time

_LAB = []
_LAB_BUDGET_S = 270.0
_kernel_fn_submitted = kernel_fn


def _log(msg):
    print(f"[lab] {msg}", flush=True)


class _Lab:
    def __init__(self):
        self.t0 = _time.monotonic()
        self.flush = torch.empty((512 << 20) // 8, dtype=torch.int64, device="cuda")

    def left(self):
        return _LAB_BUDGET_S - (_time.monotonic() - self.t0)

    def time_graph(self, fn, reps=15):
        side = torch.cuda.Stream()
        side.wait_stream(torch.cuda.current_stream())
        with torch.cuda.stream(side):
            fn()
            fn()
        torch.cuda.current_stream().wait_stream(side)
        torch.cuda.synchronize()
        graph = torch.cuda.CUDAGraph()
        with torch.cuda.graph(graph):
            fn()
        start, end = torch.cuda.Event(enable_timing=True), torch.cuda.Event(enable_timing=True)
        times = []
        for _ in range(reps):
            self.flush.fill_(1)
            start.record()
            graph.replay()
            end.record()
            torch.cuda.synchronize()
            times.append(start.elapsed_time(end) * 1000.0)
        return _st.median(times)


def _lab_inputs(batch, length, window, k_cache, v_cache, gen):
    """Scored-shape inputs: lengths as reference.py draws them (fixed 80,000 at batch 1,
    uniform +-7.5% above), scattered physical rows, page 1, scales 1."""
    dev = k_cache.device
    hq, hkv = 16, 2
    max_pages = scored_max_pages(batch, length)
    if batch == 1:
        seq = torch.full((1,), 80000, dtype=torch.int64, device=dev)
    else:
        u = torch.rand((batch,), generator=gen, device=dev)
        seq = (80000 * (1 + 0.075 * (2 * u - 1))).long()
    rows = torch.randperm(k_cache.shape[0], generator=gen, device=dev)[:batch * max_pages].to(torch.int32)
    table = rows.view(batch, max_pages)
    pos = (seq[:, None] + torch.arange(length, device=dev)).reshape(-1)
    cfg = dict(batch=batch, q_len=length, num_q_heads=hq, num_kv_heads=hkv, head_dim=64, page_size=1,
               window=window, rope_theta=500000.0 if window else 0.0,
               qk_scale_factor=5.4730064863875, sm_scale=0.125, kv_scale=1.0)
    return dict(
        qkv=torch.randn((batch, length, (2 * hq + 2 * hkv) * 64), generator=gen, device=dev).to(torch.bfloat16),
        positions=pos,
        cache_loc=torch.gather(table.long(), 1, pos.view(batch, length)).reshape(-1),
        cache_seqlens=(seq + length).to(torch.int32),
        cu_seqlens_q=torch.arange(0, batch * length + 1, length, dtype=torch.int32, device=dev),
        scheduler_metadata=None, k_cache=k_cache, v_cache=v_cache,
        k_scale=torch.tensor(1.0, device=dev), v_scale=torch.tensor(1.0, device=dev),
        page_table=table, seq_lens=seq.to(torch.int32), config=cfg)


def _variants(full, verify):
    base = TUNE[(full, verify)]
    out = [base]
    if full and not verify:
        for per_sm in (4, 8, 16, 32):
            for stages in (1, 2, 3):
                out.append((per_sm, 256, 64, 4, stages))
        out += [(16, 256, 32, 4, 2), (16, 256, 128, 4, 2), (16, 256, 64, 2, 2), (16, 256, 64, 8, 2),
                (16, 128, 64, 4, 2), (16, 512, 64, 4, 2)]
    elif full:
        for per_sm in (2, 4, 8, 16):
            for warps in (4, 8):
                for stages in (1, 2):
                    out.append((per_sm, 256, 64, warps, stages))
        out += [(4, 256, 32, 4, 2), (4, 256, 32, 8, 2)]
    else:
        for min_keys in (64, 128, 256):
            for stages in (1, 2):
                out.append((16, min_keys, 64, 4, stages))
        out += [(16, 128, 32, 4, 2), (16, 64, 32, 4, 1)]
        if verify:
            out += [(16, 128, 64, 8, 2), (16, 64, 64, 8, 1)]
    seen, uniq = set(), []
    for v in out:
        if v not in seen:
            seen.add(v)
            uniq.append(v)
    return uniq


def _lab_main():
    lab = _Lab()
    dev = torch.device("cuda")
    gen = torch.Generator(device=dev).manual_seed(1234)
    rows = 32 * scored_max_pages(32, 8)
    # Random FP8 bytes below 0x7E in magnitude (0x7F/0xFF are NaN in E4M3).
    k_cache = (torch.randint(0, 0x7E, (rows, 1, 2, 64), generator=gen, device=dev, dtype=torch.uint8)
               | (torch.randint(0, 2, (rows, 1, 2, 64), generator=gen, device=dev, dtype=torch.uint8) << 7)
               ).view(torch.float8_e4m3fn)
    k_cache = (k_cache.float() * 0.02).to(torch.float8_e4m3fn)   # keep scores in a sane range
    v_cache = (torch.randn((rows, 1, 2, 64), generator=gen, device=dev)).to(torch.float8_e4m3fn)
    _log(f"start: budget {_LAB_BUDGET_S:.0f}s, cache {rows} rows; lines: shape per_sm/min_keys/block/warps/stages nsplit us err")
    shapes = [(1, 1, 0), (16, 1, 0), (32, 1, 0), (1, 8, 0), (16, 8, 0), (32, 8, 0),
              (1, 1, 2048), (32, 1, 2048), (1, 8, 2048), (16, 8, 2048), (32, 8, 2048), (16, 1, 2048)]
    best = {}
    for batch, length, window in shapes:
        full, verify = not window, length > 1
        name = f"{'F' if full else 'S'}{'v' if verify else 'd'}{batch}"
        try:
            data = _lab_inputs(batch, length, window, k_cache, v_cache, gen)
            ref = run(data).float()
            res = []
            errors = 0
            for tune in _variants(full, verify):
                if lab.left() < 8:
                    _log(f"{name}: out of budget")
                    break
                try:
                    out = run(data, tune).float()
                    err = float((out - ref).norm() / ref.norm())
                    us = lab.time_graph(lambda: run(data, tune))
                    ns = plan(data["config"], data["page_table"].shape[1], tune)[0]
                    res.append((us, tune))
                    _log(f"{name} {'/'.join(map(str, tune))} n{ns} {us:.1f} {err:.0e}")
                except Exception as exc:
                    errors += 1   # the full reason once per shape, then just the variant
                    why = ' '.join(str(exc).split())[-300:] if errors == 1 else ''
                    _log(f"{name} {'/'.join(map(str, tune))} FAILED {type(exc).__name__} {why}")
            if res:
                best[name] = min(res)
        except Exception as exc:
            _log(f"{name}: FAILED {type(exc).__name__}: {' '.join(str(exc).split())[-300:]}")
        torch.cuda.synchronize()
    for name, (us, tune) in best.items():
        _log(f"BEST {name} {us:.1f}us {'/'.join(map(str, tune))}")
    _log(f"done in {_time.monotonic() - lab.t0:.0f}s")
    del k_cache, v_cache
    torch.cuda.empty_cache()


