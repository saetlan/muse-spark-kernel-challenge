"""Generates attention/local/cuda_ud8.py: UD8 = UD5 (make_ud5.render) with the row owners' merge spread over every warp.
L57's UD5 anatomy at Sd1 (cs16, 4 warps): the owner finalize takes 474 ns: warp 0 merges its row's 16 partials one after
another while warps 1-3 idle (16 / CS = 1 row per CTA). Here SPW = WARPS / ROWS warps work on each owned row: warp w
handles row orow = w % ROWS over sources [sub * SRC, (sub + 1) * SRC) (sub = w / ROWS, SRC = CS / SPW); sub-warps > 0
leave (m, l, o) in shared memory (the ring, free after the cluster barrier), one __syncthreads, and the sub-0 warp merges
the SPW pieces and finalizes as UD5 (its gates were prefetched for row rank + CS * warp). cs4 w4 (SPW 1) is UD5.
Host: ud8(... as ud5 ...), ud8_setup(), ud8_attrs(warps, stages, cs, grid_y).
Run: .venv/bin/python attention/local/make_ud8.py [--check]"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import make_ud5  # noqa: E402

OUT = os.path.join(HERE, "cuda_ud8.py")
VARIANTS = [(4, 3, 16), (4, 3, 8), (4, 3, 4), (8, 2, 16), (8, 3, 8)]
sub1 = make_ud5.sub1

OLD = """  if (warp >= ROWS) return;

  // ---- 9. UD4 row owner: warp w merges row hr = rank + CS * w from its own buffer, RMSNorm x sigmoid(gate), BF16 out
  {
    const int hr = static_cast<int>(rank) + CS * warp;
    float mm = -1.0e30f;
#pragma unroll
    for (int r = 0; r < CS; ++r) mm = fmaxf(mm, lbuf[(r * 16 + hr) * LBP + 64]);
    float l = 0.f, o0 = 0.f, o1 = 0.f;
#pragma unroll
    for (int r = 0; r < CS; ++r) {
      const float* pr = lbuf + (r * 16 + hr) * LBP;
      const float wt = ex2(pr[64] - mm);
      l += wt * pr[65];
      o0 += wt * pr[lane];
      o1 += wt * pr[32 + lane];
    }
"""
NEW = """  // ---- 9. UD8: SPW warps per owned row, each over SRC of the CS sources; sub-warps hand (m, l, o) to the row's
  // sub-0 warp through shared memory (the ring: free after the cluster barrier), which finalizes as UD5
  constexpr int SPW = WARPS / ROWS, SRC = CS / SPW;
  static_assert(WARPS % ROWS == 0 && CS % SPW == 0, "UD8: warps per row divide the sources");
  const int orow = warp % ROWS, sub = warp / ROWS;
  const int hr = static_cast<int>(rank) + CS * orow;
  float mm = -1.0e30f;
#pragma unroll
  for (int r = sub * SRC; r < (sub + 1) * SRC; ++r) mm = fmaxf(mm, lbuf[(r * 16 + hr) * LBP + 64]);
  float l = 0.f, o0 = 0.f, o1 = 0.f;
#pragma unroll
  for (int r = sub * SRC; r < (sub + 1) * SRC; ++r) {
    const float* pr = lbuf + (r * 16 + hr) * LBP;
    const float wt = ex2(pr[64] - mm);
    l += wt * pr[65];
    o0 += wt * pr[lane];
    o1 += wt * pr[32 + lane];
  }
  if (SPW > 1) {
    float* scr = reinterpret_cast<float*>(dsm) + (sub * ROWS + orow) * LBP;   // [SPW][ROWS][LBP]
    if (sub > 0) {
      scr[lane] = o0;
      scr[32 + lane] = o1;
      if (lane == 0) {
        scr[64] = mm;
        scr[65] = l;
      }
    }
    __syncthreads();
    if (sub > 0) return;
    float m2 = mm;
#pragma unroll
    for (int s = 1; s < SPW; ++s) m2 = fmaxf(m2, reinterpret_cast<const float*>(dsm)[(s * ROWS + orow) * LBP + 64]);
    const float w0 = ex2(mm - m2);
    l *= w0;
    o0 *= w0;
    o1 *= w0;
#pragma unroll
    for (int s = 1; s < SPW; ++s) {
      const float* ps = reinterpret_cast<const float*>(dsm) + (s * ROWS + orow) * LBP;
      const float ws = ex2(ps[64] - m2);
      l += ws * ps[65];
      o0 += ws * ps[lane];
      o1 += ws * ps[32 + lane];
    }
  }
  {
"""


def render(variants=None):
    text = make_ud5.render(variants or VARIANTS)
    for old, new in (("okc_ud5", "okc_ud8"), ("OKC_UD5_", "OKC_UD8_"), ("CUDA_UD5_", "CUDA_UD8_"), ("UD5_VARIANTS", "UD8_VARIANTS"),
                     ("ud5(", "ud8("), ("ud5_setup", "ud8_setup"), ("ud5_attrs", "ud8_attrs"), ("ud5_kernel", "ud8_kernel"), ('"ud5', '"ud8')):
        text = text.replace(old, new)
    text = sub1(text, OLD, NEW, "finalize")
    i = text.index('"""', 3) + 3
    return ('"""Generated by make_ud8.py from make_ud5.render (do not edit): UD8, UD5 with the owners\' merge over every warp\n'
            '(see make_ud8.py). Original docstring follows.\n' + text[3:i] + text[i:])


def sim():
    """For each variant: the (orow, sub) pairs cover each owned row's CS sources exactly once; the two-level merge equals
    the direct merge on random partials; scratch rows stay inside the ring; formulas asserted present."""
    import math
    import random
    t = render()
    for frag in ("const int orow = warp % ROWS, sub = warp / ROWS;", "for (int r = sub * SRC; r < (sub + 1) * SRC; ++r)",
                 "float* scr = reinterpret_cast<float*>(dsm) + (sub * ROWS + orow) * LBP;", "const float w0 = ex2(mm - m2);"):
        assert t.count(frag) >= 1, frag
    rnd = random.Random(8)
    for w, s, cs in VARIANTS:
        rows = 16 // cs
        spw, src = w // rows, cs // (w // rows)
        assert w % rows == 0 and cs % spw == 0
        assert spw * rows * 68 * 4 <= w * s * 2 * 16 * 144
        for orow in range(rows):
            got = sorted(r for warp in range(w) if warp % rows == orow for r in range(warp // rows * src, (warp // rows + 1) * src))
            assert got == list(range(cs)), (w, s, cs, orow, got)
            parts = [(rnd.uniform(-20, 4), rnd.uniform(0.1, 3), rnd.gauss(0, 1)) for _ in range(cs)]
            pieces = []
            for sub in range(spw):
                ps = parts[sub * src:(sub + 1) * src]
                mm = max(p[0] for p in ps)
                pieces.append((mm, sum(2 ** (p[0] - mm) * p[1] for p in ps), sum(2 ** (p[0] - mm) * p[2] for p in ps)))
            m2 = max(p[0] for p in pieces)
            l = sum(2 ** (p[0] - m2) * p[1] for p in pieces)
            o = sum(2 ** (p[0] - m2) * p[2] for p in pieces)
            M = max(p[0] for p in parts)
            L = sum(2 ** (p[0] - M) * p[1] for p in parts)
            O = sum(2 ** (p[0] - M) * p[2] for p in parts)
            assert math.isclose(o / l, O / L, rel_tol=1e-9, abs_tol=1e-12)
    return True


if __name__ == "__main__":
    sim()
    text = render()
    if "--check" in sys.argv:
        same = os.path.exists(OUT) and open(OUT).read() == text
        print("cuda_ud8.py up to date" if same else "cuda_ud8.py STALE")
        sys.exit(0 if same else 1)
    open(OUT, "w").write(text)
    print(f"wrote {OUT} (merge-split model ok)")
