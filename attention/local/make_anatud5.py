"""Generates attention/local/cuda_anatud5.py: UD5 (make_ud5.render, variants (4,3,16), (4,3,8), (4,3,4): v15's Sd1 / Sd16 /
Sd32 kernels) with the same anatomy stamps as make_anatud4.py (slots: 0 globaltimer entry, 1 clock entry, 2 seqlens
arrived, 3 page entries landed, 4 RoPE table, 5 query fold, 6 first chunk landed, 7 loop end, 8 accumulated K/V waits,
9 warps' partials in smem, 10 CTA weights done, 11 after the push's cluster barrier, 13 chunks, 28 / 29 exit, 30 SM id),
to find where v15's sliding decode still spends its time after AF70's fixes (UD5 Sd1 6.9 us on the judge vs a ~4.3 us
bare one-launch chain, AF57). Anchors as make_anatud4.py (the warp-partial store anchor is UD5's padded one).
Run: .venv/bin/python attention/local/make_anatud5.py [--check]"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import make_ud5  # noqa: E402
from make_anatomy import LOOP_WAIT, MERGE_SYNC, common, sub1  # noqa: E402

OUT = os.path.join(HERE, "cuda_anatud5.py")
MERGE_SYNC5 = MERGE_SYNC.replace("32 * (t4 & 1) + 16 * jj + j", "33 * (t4 & 1) + 16 * jj + j")


def make():
    ns = {}
    exec(make_ud5.render([(4, 3, 16), (4, 3, 8), (4, 3, 4)]), ns)
    src, decl = ns["CUDA_UD5_SRC"], ns["CUDA_UD5_DECL"]
    src = src.replace("okc_ud5_info", "okc_info5")
    src, decl = common(src, decl, "okc_ud5", "ud5", "an_ud5",
                       "    int hq, int hkv, int max_pages, int nsplit, int page, int window, int rope, float qk_factor, float sm_scale) {",
                       "static_cast<int>(rope), static_cast<float>(qk_factor), static_cast<float>(sm_scale)",
                       "int64_t rope, double qk_factor, double sm_scale, int64_t warps, int64_t stages, int64_t cs) {",
                       "double sm_scale, int64_t warps, int64_t stages, int64_t cs);")
    src = sub1(src, "  // ---- 2. the slice; page entries\n", "  AN_DEP(2, n);\n  // ---- 2. the slice; page entries\n", "seqlens")
    src = sub1(src, "    __syncthreads();\n  }\n\n  // ---- 4. page entries landed",
               "    __syncthreads();\n  }\n  AN_PUT(4, an_clk_m());\n\n  // ---- 4. page entries landed", "rope")
    src = sub1(src, "  // ---- 4. page entries landed: the first STAGES - 1 stages of K/V rows\n"
                    "  asm volatile(\"cp.async.wait_group 0;\");\n  __syncwarp();\n",
               "  // ---- 4. page entries landed: the first STAGES - 1 stages of K/V rows\n"
               "  asm volatile(\"cp.async.wait_group 0;\");\n  __syncwarp();\n  AN_PUT(3, an_clk_m());\n  AN_PUT(13, mine);\n",
               "page entries")
    src = sub1(src, "  if (has_new) __syncthreads();                               // new_k / new_v visible to every warp\n",
               "  if (has_new) __syncthreads();                               // new_k / new_v visible to every warp\n"
               "  AN_DEP(5, qa[7][0]);\n", "fold")
    src = sub1(src, LOOP_WAIT,
               "  unsigned long long an_wacc = 0;\n" + LOOP_WAIT.replace(
                   "    asm volatile(\"cp.async.wait_group %0;\"", "    const unsigned long long an_w0 = an_clk();\n"
                   "    asm volatile(\"cp.async.wait_group %0;\"")
               + "    const unsigned long long an_w1 = an_clk();\n    an_wacc += an_w1 - an_w0;\n"
                 "    if (i == 0) AN_PUT(6, an_w1);\n", "loop wait")
    src = sub1(src, "  asm volatile(\"cp.async.wait_all;\");\n  __syncthreads();                     // every warp",
               "  AN_PUT(7, an_clk_m());\n  AN_PUT(8, an_wacc);\n"
               "  asm volatile(\"cp.async.wait_all;\");\n  __syncthreads();                     // every warp", "loop end")
    src = sub1(src, MERGE_SYNC5, MERGE_SYNC5 + "  AN_PUT(9, an_clk_m());\n", "warp merge")
    src = sub1(src, "  // ---- 8. push the partial", "  AN_PUT(10, an_clk_m());\n  // ---- 8. push the partial", "weights")
    src = sub1(src, "  cluster_sync();                                   // every partial in its owner's buffer\n"
                    "  if (warp >= ROWS) return;\n",
               "  cluster_sync();                                   // every partial in its owner's buffer\n"
               "  AN_PUT(11, an_clk_m());\n  if (warp >= ROWS) { if (warp == 0) AN_END(); return; }\n", "push barrier")
    src = sub1(src, "    op[32 + lane] = f2bf16(o1 * rn / (1.f + __expf(-gate1)));\n  }\n}\n",
               "    op[32 + lane] = f2bf16(o1 * rn / (1.f + __expf(-gate1)));\n  }\n  AN_END();\n}\n", "owner end")
    return src, decl


def render():
    src, decl = make()
    return ('"""Generated by make_anatud5.py (do not edit): UD5 with anatomy stamps; see make_anatud5.py for the slots."""\n'
            f"\nCUDA_AN_UD5_SRC = r\"\"\"{src}\"\"\"\n\nCUDA_AN_UD5_DECL = {decl!r}\n")


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        same = os.path.exists(OUT) and open(OUT).read() == text
        print("cuda_anatud5.py up to date" if same else "cuda_anatud5.py STALE")
        sys.exit(0 if same else 1)
    open(OUT, "w").write(text)
    print(f"wrote {OUT} ({len(text)} bytes)")
