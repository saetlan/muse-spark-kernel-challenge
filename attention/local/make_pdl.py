"""Generates the programmatic-dependent-launch (PDL) variants of verified code by exact edits:
  submission.py's Triton chain        -> pdl_block.py (_prologue_p, _attend_p, _combine_p, run_pdl)
  cuda_dec3.py (D2), cuda_dec4.py (D3) -> cuda_dec3p.py (D2p), cuda_dec4p.py (D3p)

PDL (PTX ISA 9.4 sec. 9.7.15.14; Triton v3.8.0 `launch_pdl` launch option + gdc.py; CUDA
cudaLaunchKernelEx with cudaLaunchAttributeProgrammaticStreamSerialization): a dependent kernel
may start while its prerequisite runs; `griddepcontrol.wait` blocks until the prerequisite grid has
completed and its memory is visible; `griddepcontrol.launch_dependents` lets the dependent be
scheduled once every CTA of the current grid issued it (or exited). Rules kept here
(TRACKER.md checklist 8): every dependent waits before reading any producer output and before any
global write; nothing before the wait touches memory a producer writes.
- Triton: _prologue_p / _attend_p trigger dependents either first thing (TRIGGER_EARLY) or after
  their last store (late, the checklist's default); _attend_p and _combine_p wait first thing.
  run_pdl launches _attend_p and _combine_p with launch_pdl=True.
- D2p: wait first thing in the kernel; trigger early or after the partial stores (template flag).
- D3p: the page-entry prologue (inputs only: page table) is issued BEFORE the wait, so its round
  trip overlaps the prologue kernel; the wait comes before the query loads and any K/V copy (the
  prologue writes the new token's row). Host launches use cudaLaunchKernelEx + the PDL attribute.
Usage: .venv/bin/python attention/local/make_pdl.py [--check]"""
import ast
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROB = os.path.dirname(HERE)
CHECK = "--check" in sys.argv


def sub1(text, old, new):
    assert text.count(old) == 1, f"anchor found {text.count(old)} times: {old[:90]!r}"
    return text.replace(old, new)


def emit(path, text):
    if CHECK:
        same = os.path.exists(path) and open(path).read() == text
        print(("up to date: " if same else "STALE: ") + path)
        if not same:
            sys.exit(1)
        return
    open(path, "w").write(text)
    print("wrote", path)


# ---------------------------------------------------------------- Triton chain
def func_source(src, tree, name):
    for n in tree.body:
        if isinstance(n, ast.FunctionDef) and n.name == name:
            lines = src.splitlines(keepends=True)
            start = min([d.lineno for d in n.decorator_list] + [n.lineno]) - 1
            return "".join(lines[start:n.end_lineno]), n
    raise KeyError(name)


def insert_first(fsrc, node, src_lines_offset, stmt):
    """Insert `stmt` (one line, no indent) before the function's first body statement."""
    lines = fsrc.splitlines(keepends=True)
    first = node.body[0].lineno - src_lines_offset
    indent = re.match(r"\s*", lines[first]).group(0)
    lines.insert(first, indent + stmt + "\n")
    return "".join(lines)


def make_triton_block():
    src = open(os.path.join(PROB, "submission.py")).read()
    tree = ast.parse(src)
    out = ['''

# =============================================================================================
# PDL variant of v2.2's Triton chain (generated by attention/local/make_pdl.py; see its docstring).
# _prologue_p / _attend_p trigger their dependents first thing (TRIGGER_EARLY) or after their last
# store; _attend_p and _combine_p (launched with launch_pdl=True) wait first thing.
# =============================================================================================
import triton.language.extra.cuda as tlcuda
''']
    for name in ("_prologue", "_attend", "_combine"):
        fsrc, node = func_source(src, tree, name)
        offset = min([d.lineno for d in node.decorator_list] + [node.lineno])
        fsrc = fsrc.replace(f"def {name}(", f"def {name}_p(", 1)
        if name in ("_prologue", "_attend"):
            fsrc = sub1(fsrc, "EPS: tl.constexpr):" if name == "_prologue" else "BLOCK: tl.constexpr):",
                        ("EPS: tl.constexpr, TRIGGER_EARLY: tl.constexpr):" if name == "_prologue"
                         else "BLOCK: tl.constexpr, TRIGGER_EARLY: tl.constexpr):"))
        if name == "_prologue":
            fsrc = insert_first(fsrc, node, offset, "if TRIGGER_EARLY:\n        tlcuda.gdc_launch_dependents()")
            fsrc = fsrc.rstrip("\n") + "\n    if not TRIGGER_EARLY:\n        tlcuda.gdc_launch_dependents()\n"
        elif name == "_attend":
            fsrc = insert_first(fsrc, node, offset,
                                "tlcuda.gdc_wait()   # the prologue's q and new cache row are visible after this\n"
                                "    if TRIGGER_EARLY:\n        tlcuda.gdc_launch_dependents()")
            fsrc = fsrc.rstrip("\n") + "\n    if not TRIGGER_EARLY:\n        tlcuda.gdc_launch_dependents()\n"
        else:
            fsrc = insert_first(fsrc, node, offset, "tlcuda.gdc_wait()   # the attention partials are visible after this")
        out.append("\n\n" + fsrc)
    rsrc, _ = func_source(src, tree, "run")
    rsrc = rsrc.replace("def run(data, tune=None):", "def run_pdl(data, tune=None, early=False):", 1)
    rsrc = sub1(rsrc, "_prologue[(tokens,)](", "_prologue_p[(tokens,)](")
    rsrc = sub1(rsrc, "QK_FACTOR=cfg[\"qk_scale_factor\"], EPS=RMS_EPS,\n                         num_warps=4)",
                "QK_FACTOR=cfg[\"qk_scale_factor\"], EPS=RMS_EPS,\n                         TRIGGER_EARLY=early, num_warps=4)")
    rsrc = sub1(rsrc, "_attend[(batch, hkv // 2, nsplit)](", "_attend_p[(batch, hkv // 2, nsplit)](")
    rsrc = sub1(rsrc, "MP=mp, BLOCK=block, num_warps=warps, num_stages=stages)",
                "MP=mp, BLOCK=block, TRIGGER_EARLY=early, num_warps=warps, num_stages=stages,\n        launch_pdl=True)")
    rsrc = sub1(rsrc, "_combine[(tokens, hq)](", "_combine_p[(tokens, hq)](")
    rsrc = sub1(rsrc, "HQ=hq, HKV=hkv, EPS=RMS_EPS, CB=cb, num_warps=4)",
                "HQ=hq, HKV=hkv, EPS=RMS_EPS, CB=cb, num_warps=4, launch_pdl=True)")
    out.append("\n\n" + rsrc)
    emit(os.path.join(HERE, "pdl_block.py"), "".join(out))


# ---------------------------------------------------------------- CUDA (D2p, D3p)
LAUNCH_HELPER = '''
// Launch with the programmatic-stream-serialization attribute (PDL): the kernel may start while the
// previous kernel on the stream runs; it waits (griddepcontrol.wait) before using its outputs.
template <typename... ExpTypes, typename... ActTypes>
static void launch_pdl(void (*kernel)(ExpTypes...), dim3 grid, unsigned threads, size_t smem, cudaStream_t stream,
                       ActTypes&&... args) {
  cudaLaunchConfig_t cfg = {};
  cfg.gridDim = grid;
  cfg.blockDim = dim3(threads, 1, 1);
  cfg.dynamicSmemBytes = smem;
  cfg.stream = stream;
  cudaLaunchAttribute attr[1];
  attr[0].id = cudaLaunchAttributeProgrammaticStreamSerialization;
  attr[0].val.programmaticStreamSerializationAllowed = 1;
  cfg.attrs = attr;
  cfg.numAttrs = 1;
  const cudaError_t e = cudaLaunchKernelEx(&cfg, kernel, static_cast<ActTypes&&>(args)...);
  TORCH_CHECK(e == cudaSuccess, "PDL launch failed: ", cudaGetErrorString(e));
}
'''
WAIT = '  asm volatile("griddepcontrol.wait;" ::: "memory");   // producer done, its writes visible\n'
TRIG = '  asm volatile("griddepcontrol.launch_dependents;" ::: "memory");\n'


def cuda_launches(src, ns, kern, args_macro):
    """kernel<<<grid, T, smem, stream>>>(ARGS) -> launch_pdl(kernel, grid, T, smem, stream, ARGS)."""
    pat = re.compile(r"(%s::%s<[^>]*>)<<<grid, (\d+), smem, stream>>>\(%s\);" % (ns, kern, args_macro))
    new, n = pat.subn(lambda m: f"launch_pdl({m.group(1)}, grid, {m.group(2)}, smem, stream, {args_macro});", src)
    assert n >= 3, f"expected the variant launches, found {n}"
    return new


def make_d2p():
    text = open(os.path.join(HERE, "cuda_dec3.py")).read()
    _, rest = text.split('CUDA_DEC3_SRC = r"""', 1)
    src = 'CUDA_DEC3_SRC = r"""' + rest
    src = src.replace("dec3", "dec3p").replace("DEC3", "DEC3P")
    src = sub1(src, "template <int WARPS, int STAGES>\n__global__",
               "template <int WARPS, int STAGES, bool EARLY>\n__global__")
    src = sub1(src, "  // Stacked block-diagonal query fragments",
               WAIT + "  if (EARLY) asm volatile(\"griddepcontrol.launch_dependents;\" ::: \"memory\");\n"
               "  // Stacked block-diagonal query fragments")
    # late trigger: after the partial stores (end of kernel)
    src = sub1(src, "      l_part[part] = l;\n    }\n  }\n}\n", "      l_part[part] = l;\n    }\n  }\n"
               "  if (!EARLY) asm volatile(\"griddepcontrol.launch_dependents;\" ::: \"memory\");\n}\n")
    src = sub1(src, "}  // namespace okc_dec3p\n", LAUNCH_HELPER + "\n}  // namespace okc_dec3p\n")
    src = finish_host(src, "okc_dec3p", "attend_dec3p_kernel", "OKC_DEC3P_ARGS", "attend_dec3p",
                      [(8, 2), (8, 3), (4, 4), (4, 3)])
    doc = ('"""D2p: D2 (cuda_dec3.py) as a PDL dependent (generated by make_pdl.py; see its docstring):\n'
           'launched with cudaLaunchKernelEx + programmatic stream serialization; waits on the Triton prologue\n'
           'first thing; triggers its dependent (the Triton merge) early or after its stores.\n"""\n\n')
    emit(os.path.join(HERE, "cuda_dec3p.py"), doc + src)


def finish_host(src, ns, kern, args_macro, fname, variants):
    """Host side: an `early` argument picks the template flag; every launch goes through launch_pdl."""
    src = sub1(src, "double sm_scale, int64_t warps, int64_t stages) {\n  auto stream",
               "double sm_scale, int64_t warps, int64_t stages, int64_t early) {\n  auto stream")
    src = src.replace("int64_t warps, int64_t stages);\\n\"", "int64_t warps, int64_t stages, int64_t early);\\n\"")
    # launches: duplicate each variant for EARLY true/false
    pat = re.compile(r"(%s::%s<(\d), (\d)>)<<<grid, (\d+), smem, stream>>>\(%s\);" % (ns, kern, args_macro))

    def rep(m):
        w, s, t = m.group(2), m.group(3), m.group(4)
        return (f"{{ if (early) {ns}::launch_pdl({ns}::{kern}<{w}, {s}, true>, grid, {t}, smem, stream, {args_macro}); "
                f"else {ns}::launch_pdl({ns}::{kern}<{w}, {s}, false>, grid, {t}, smem, stream, {args_macro}); }}")
    src, n = pat.subn(rep, src)
    assert n == len(variants), f"{n} launches"
    # setup / attrs: both template flags
    for w, s in variants:
        old = f"cudaFuncSetAttribute({ns}::{kern}<{w}, {s}>, cudaFuncAttributeMaxDynamicSharedMemorySize, {w} * {s} * STAGE_BYTES);"
        new = (f"cudaFuncSetAttribute({ns}::{kern}<{w}, {s}, true>, cudaFuncAttributeMaxDynamicSharedMemorySize, {w} * {s} * STAGE_BYTES);\n"
               f"  err |= cudaFuncSetAttribute({ns}::{kern}<{w}, {s}, false>, cudaFuncAttributeMaxDynamicSharedMemorySize, {w} * {s} * STAGE_BYTES);")
        src = sub1(src, old, new)
        src = sub1(src, f"cudaFuncGetAttributes(&a, {ns}::{kern}<{w}, {s}>);", f"cudaFuncGetAttributes(&a, {ns}::{kern}<{w}, {s}, false>);")
    return src


def make_d3p():
    text = open(os.path.join(HERE, "cuda_dec4.py")).read()
    _, rest = text.split('CUDA_DEC4_SRC = r"""', 1)
    src = 'CUDA_DEC4_SRC = r"""' + rest
    src = src.replace("dec4", "dec4p").replace("DEC4", "DEC4P")
    src = sub1(src, "template <int WARPS, int STAGES>\n__global__",
               "template <int WARPS, int STAGES, bool EARLY>\n__global__")
    # Move the ring setup + page-entry prologue ahead of the query loads; wait after issuing it.
    q_anchor = "  // Stacked block-diagonal query fragments"
    pt_line = "  const int* pt = page_table + static_cast<long>(b) * max_pages;\n"
    ring_start = "  extern __shared__ __align__(16) uint8_t dsm[];\n"
    pro_wait = ('  asm volatile("cp.async.commit_group;");\n  asm volatile("cp.async.wait_group 0;");\n  __syncwarp();\n'
                "#pragma unroll\n  for (int i = 0; i < STAGES - 1; ++i) issue(i);\n")
    a = src.index(ring_start)
    b = src.index(pro_wait)
    ring_setup = src[a:b] + '  asm volatile("cp.async.commit_group;");\n'   # through the page-entry commit
    src = src[:a] + ('  asm volatile("cp.async.wait_group 0;");\n  __syncwarp();\n'
                     "#pragma unroll\n  for (int i = 0; i < STAGES - 1; ++i) issue(i);\n") + src[b + len(pro_wait):]
    src = sub1(src, pt_line, "")
    src = sub1(src, q_anchor,
               "  // ---- PDL: page entries first (inputs only), then wait for the prologue kernel (q, new row).\n"
               + pt_line + ring_setup + WAIT
               + "  if (EARLY) asm volatile(\"griddepcontrol.launch_dependents;\" ::: \"memory\");\n" + q_anchor)
    src = sub1(src, "      l_part[part] = l;\n    }\n  }\n}\n", "      l_part[part] = l;\n    }\n  }\n"
               "  if (!EARLY) asm volatile(\"griddepcontrol.launch_dependents;\" ::: \"memory\");\n}\n")
    src = sub1(src, "}  // namespace okc_dec4p\n", LAUNCH_HELPER + "\n}  // namespace okc_dec4p\n")
    src = finish_host(src, "okc_dec4p", "attend_dec4p_kernel", "OKC_DEC4P_ARGS", "attend_dec4p",
                      [(8, 2), (8, 3), (4, 4), (4, 3)])
    doc = ('"""D3p: D3 (cuda_dec4.py) as a PDL dependent (generated by make_pdl.py; see its docstring): the\n'
           'page-entry prologue is issued before griddepcontrol.wait (its round trip overlaps the Triton\n'
           'prologue kernel); queries and K/V copies come after the wait; early or late trigger.\n"""\n\n')
    emit(os.path.join(HERE, "cuda_dec4p.py"), doc + src)


if __name__ == "__main__":
    make_triton_block()
    make_d2p()
    make_d3p()
