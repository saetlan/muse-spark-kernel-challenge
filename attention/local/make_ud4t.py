"""Generates attention/local/cuda_ud4t.py: UD4t = UD4 (cuda_ud4.py, sliding decode) with D3t's TMA bulk copies
(make_dec4t.py: one 128 B cp.async.bulk per K / V row of each 16-key chunk into the warp's row-major ring, per-(warp,
stage) data mbarriers with expect-tx, page entries in D3's cp.async groups; UD4's ring code is D3's). UD4's new-row patch
writes the chunk's stage after the data barrier, so it still overrides the possibly stale cache row (AF36). Watchdog.
Host: ud4t(... as ud4 ...), ud4t_setup(), ud4t_attrs(), ud4t_hang().
Run: .venv/bin/python attention/local/make_ud4t.py [--check]"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import make_dec4t  # noqa: E402

OUT = os.path.join(HERE, "cuda_ud4t.py")
sub1 = make_dec4t.sub1


def render():
    text = open(os.path.join(HERE, "cuda_ud4.py")).read()
    for pat, rep in ((r"\bokc_ud4", "okc_ud4t"), (r"\bOKC_UD4_", "OKC_UD4T_"), (r"\bud4\(", "ud4t("), (r"\bud4_setup\b", "ud4t_setup"),
                     (r"\bud4_attrs\b", "ud4t_attrs"), (r"\bud4_kernel\b", "ud4t_kernel"), (r"\bCUDA_UD4_", "CUDA_UD4T_")):
        text = re.sub(pat, rep, text)
    helpers = make_dec4t.HELPERS.replace("okc_dec4t_hang", "okc_ud4t_hang").replace("make_dec4t.py", "make_ud4t.py").replace("D3t:", "UD4t:")
    text = sub1(text, "template <int WARPS, int STAGES, int CS>\n__global__", helpers + "template <int WARPS, int STAGES, int CS>\n__global__", "helpers")
    text = sub1(text, "  uint8_t* ring = dsm + static_cast<long>(warp) * STAGES * STAGE_BYTES;\n",
                "  uint8_t* ring = dsm + static_cast<long>(warp) * STAGES * STAGE_BYTES;\n"
                "  __shared__ __align__(8) uint64_t dbar[WARPS][STAGES];   // UD4t: chunk data barriers per (warp, stage)\n"
                "  if (lane == 0) {\n"
                "#pragma unroll\n"
                "    for (int s = 0; s < STAGES; ++s) asm volatile(\"mbarrier.init.shared::cta.b64 [%0], 1;\" ::\"r\"(smem_u32(&dbar[warp][s])));\n"
                "    asm volatile(\"fence.mbarrier_init.release.cluster;\" ::: \"memory\");\n"
                "  }\n"
                "  __syncwarp();\n", "barrier init")
    text = sub1(text, """      uint8_t* st = ring + (i % STAGES) * STAGE_BYTES;
#pragma unroll
      for (int qq = 0; qq < 4; ++qq) {
        const int tok = qq * 4 + (lane >> 3), ch = lane & 7;
        const long row = __shfl_sync(FULL, my_row, tok);
        cp16(st + tok * PITCH + 16 * ch, kc + row * row_bytes + poff + 16 * ch);
        cp16(st + CHUNK * PITCH + tok * PITCH + 16 * ch, vc + row * row_bytes + poff + 16 * ch);
      }
""", """      uint8_t* st = ring + (i % STAGES) * STAGE_BYTES;
      {   // UD4t: lane l < 16: the K row of token l, lane l >= 16: the V row of token l - 16 (one 128 B bulk copy each)
        if (lane == 0) bar_expect_tx(&dbar[warp][i % STAGES], 2u * CHUNK * 128u);
        __syncwarp();
        asm volatile("fence.proxy.async.shared::cta;" ::: "memory");
        const int tk = lane & 15;
        if (lane < CHUNK) bulk128(st + tk * PITCH, kc + my_row * row_bytes + poff, &dbar[warp][i % STAGES]);
        else bulk128(st + CHUNK * PITCH + tk * PITCH, vc + my_row * row_bytes + poff, &dbar[warp][i % STAGES]);
      }
""", "issue copies")
    text = sub1(text, """    issue(i + STAGES - 1);
    asm volatile("cp.async.wait_group %0;" ::"n"(STAGES - 1));
    __syncwarp();
""", """    issue(i + STAGES - 1);
    asm volatile("cp.async.wait_group %0;" ::"n"(STAGES - 1));   // page entries
    __syncwarp();
    mbar_wait(&dbar[warp][i % STAGES], static_cast<uint32_t>((i / STAGES) & 1));   // UD4t: chunk i's rows landed
""", "loop wait")
    host = ('\nint64_t ud4t_hang() {   // lab: 1 when a UD4t barrier wait gave up (watchdog); reads and clears the flag\n'
            '  unsigned int h = 0, z = 0;\n'
            '  cudaMemcpyFromSymbol(&h, okc_ud4t::okc_ud4t_hang, sizeof(h));\n'
            '  cudaMemcpyToSymbol(okc_ud4t::okc_ud4t_hang, &z, sizeof(z));\n'
            '  return h;\n}\n')
    k = text.index('"""\n\nCUDA_UD4T_DECL = ')
    text = text[:k] + host + text[k:]
    m = re.search(r"CUDA_UD4T_DECL = '(.*?)'\n", text, re.S)
    assert m
    line = text[m.start():m.end()]
    ns = {}
    exec(line, ns)
    text = text.replace(line, "CUDA_UD4T_DECL = " + repr(ns["CUDA_UD4T_DECL"] + "\nint64_t ud4t_hang();") + "\n")
    i = text.index('"""', 3) + 3
    return ('"""Generated by make_ud4t.py from cuda_ud4.py (do not edit): UD4t, UD4 with D3t\'s TMA bulk copies (see\n'
            'make_ud4t.py). Original docstring follows.\n' + text[3:i] + text[i:])


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        same = os.path.exists(OUT) and open(OUT).read() == text
        print("cuda_ud4t.py up to date" if same else "cuda_ud4t.py STALE")
        sys.exit(0 if same else 1)
    open(OUT, "w").write(text)
    print(f"wrote {OUT}")
