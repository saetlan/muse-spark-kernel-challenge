"""Generates attention/local/cuda_uw2v.py: UW2v = UW2 (cuda_uw2.py) with 16-byte DSMEM pushes. AF62: UW2's push to
the row owners (each consumer lane: 2 rows x 8 `st.shared::cluster.v2.f32` + m / l scalars) costs 1.95 us at Sv1.
Here lane pairs (t4, t4 ^ 1) swap one half's two columns per 8-column group with __shfl_xor 1, so even-t4 lanes hold
4 contiguous columns of row half 0 and odd-t4 lanes 4 of row half 1, and each lane issues 8 `st.shared::cluster.v4.f32`
instead of 16 v2 (half the remote store instructions, same bytes, same destinations). m / l stores unchanged.
Only the push loop changes (asserted anchor); everything else UW2 byte for byte (renames).
Host: uw2v(... as uw2 ...), uw2v_setup(), uw2v_attrs().
Run: .venv/bin/python attention/local/make_uw2v.py [--check]"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "cuda_uw2v.py")

OLD = """#pragma unroll
    for (int half = 0; half < 2; ++half) {
      float l = l_run[half];
      l += __shfl_xor_sync(FULL, l, 1);
      l += __shfl_xor_sync(FULL, l, 2);
      const int R = (2 * w + half) * 16 + h * 8 + g;
      const uint32_t row = map_rank(smem_u32(rbuf), static_cast<uint32_t>(R / RPC)) +
                           static_cast<uint32_t>((static_cast<int>(rank) * RPC + R % RPC) * LBP * 4);
#pragma unroll
      for (int j = 0; j < 8; ++j) st_cluster2(row + (8 * j + 2 * t4) * 4, o[4 * j + 2 * half], o[4 * j + 2 * half + 1]);
      if (t4 == 0) {
        st_cluster(row + 64 * 4, m_run[half]);
        st_cluster(row + 65 * 4, l);
      }
    }
"""
NEW = """#pragma unroll
    for (int half = 0; half < 2; ++half) {   // UW2v: m / l as UW2
      float l = l_run[half];
      l += __shfl_xor_sync(FULL, l, 1);
      l += __shfl_xor_sync(FULL, l, 2);
      const int R = (2 * w + half) * 16 + h * 8 + g;
      const uint32_t row = map_rank(smem_u32(rbuf), static_cast<uint32_t>(R / RPC)) +
                           static_cast<uint32_t>((static_cast<int>(rank) * RPC + R % RPC) * LBP * 4);
      if (t4 == 0) {
        st_cluster(row + 64 * 4, m_run[half]);
        st_cluster(row + 65 * 4, l);
      }
    }
    {   // UW2v: o as 16 B stores. Even t4: row half 0, columns 8j + 2t4 .. +3 (own 2, then the odd partner's half-0
        // pair); odd t4: row half 1, columns 8j + 2(t4 - 1) .. +3 (the even partner's half-1 pair, then own 2).
      const int odd = t4 & 1;
      const int R = (2 * w + odd) * 16 + h * 8 + g;
      const uint32_t row = map_rank(smem_u32(rbuf), static_cast<uint32_t>(R / RPC)) +
                           static_cast<uint32_t>((static_cast<int>(rank) * RPC + R % RPC) * LBP * 4);
      const int c0 = 2 * (t4 & 2);
#pragma unroll
      for (int j = 0; j < 8; ++j) {
        const float s0 = odd ? o[4 * j] : o[4 * j + 2];
        const float s1 = odd ? o[4 * j + 1] : o[4 * j + 3];
        const float r0 = __shfl_xor_sync(FULL, s0, 1);
        const float r1 = __shfl_xor_sync(FULL, s1, 1);
        if (odd) st_cluster4(row + (8 * j + c0) * 4, r0, r1, o[4 * j + 2], o[4 * j + 3]);
        else st_cluster4(row + (8 * j + c0) * 4, o[4 * j], o[4 * j + 1], r0, r1);
      }
    }
"""


def render():
    text = open(os.path.join(HERE, "cuda_uw2.py")).read()
    for pat, rep in ((r"\bokc_uw2", "okc_uw2v"), (r"\bOKC_UW2_", "OKC_UW2V_"), (r"\buw2\(", "uw2v("), (r"\buw2_setup\b", "uw2v_setup"),
                     (r"\buw2_attrs\b", "uw2v_attrs"), (r"\buw2_kernel\b", "uw2v_kernel"), (r"\bCUDA_UW2_", "CUDA_UW2V_"),
                     (r'"uw2: ', '"uw2v: '), (r'"uw2 ', '"uw2v ')):
        text = re.sub(pat, rep, text)
    assert text.count(OLD) == 1, text.count(OLD)
    text = text.replace(OLD, NEW)
    i = text.index('"""', 3) + 3
    return ('"""Generated by make_uw2v.py from cuda_uw2.py (do not edit): UW2v, UW2 with 16-byte DSMEM pushes (see\n'
            'make_uw2v.py). Original docstring follows.\n' + text[3:i] + text[i:])


def sim():
    """Lane-level model of the swap: every (row half, column) of every (g, t4) pair lands once, with its own value.
    The model's formulas are the source's: each is asserted present in NEW verbatim."""
    import itertools
    for frag in ("const int c0 = 2 * (t4 & 2);", "const float s0 = odd ? o[4 * j] : o[4 * j + 2];",
                 "const float s1 = odd ? o[4 * j + 1] : o[4 * j + 3];", "const int R = (2 * w + odd) * 16 + h * 8 + g;",
                 "if (odd) st_cluster4(row + (8 * j + c0) * 4, r0, r1, o[4 * j + 2], o[4 * j + 3]);",
                 "else st_cluster4(row + (8 * j + c0) * 4, o[4 * j], o[4 * j + 1], r0, r1);",
                 "const float r0 = __shfl_xor_sync(FULL, s0, 1);", "const float r1 = __shfl_xor_sync(FULL, s1, 1);"):
        assert NEW.count(frag) == 1, frag
    for g in range(8):
        dest = {}
        o = {t4: [("v", t4, k) for k in range(32)] for t4 in range(4)}   # o[4j + 2 half + e] = col 8j + 2t4 + e of half
        for t4 in range(4):
            odd, c0 = t4 & 1, 2 * (t4 & 2)
            for j in range(8):
                p = t4 ^ 1
                s0 = o[p][4 * j] if p & 1 else o[p][4 * j + 2]     # what the partner sends
                s1 = o[p][4 * j + 1] if p & 1 else o[p][4 * j + 3]
                vals = (s0, s1, o[t4][4 * j + 2], o[t4][4 * j + 3]) if odd else (o[t4][4 * j], o[t4][4 * j + 1], s0, s1)
                for e, v in enumerate(vals):
                    key = (odd, 8 * j + c0 + e)
                    assert key not in dest, key
                    dest[key] = v
        for half, col in itertools.product(range(2), range(64)):
            j, r = divmod(col, 8)
            src_t4, e = divmod(r, 2)
            assert dest[(half, col)] == ("v", src_t4, 4 * j + 2 * half + e), (half, col, dest[(half, col)])
    return True


if __name__ == "__main__":
    sim()
    text = render()
    if "--check" in sys.argv:
        same = os.path.exists(OUT) and open(OUT).read() == text
        print("cuda_uw2v.py up to date" if same else "cuda_uw2v.py STALE")
        sys.exit(0 if same else 1)
    open(OUT, "w").write(text)
    print(f"wrote {OUT} (swap model ok)")
