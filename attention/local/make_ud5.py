"""Generates attention/local/cuda_ud5.py: UD5 = UD4c (cuda_ud4c.py: UD4 + clusters 2..16 + occupancy) with L46's
anatomy fixes (AF70), by asserted substitutions:
1. bank-conflict-free warp partials: UD4 stores each warp's o to sm_o[warp][hl][g][32 (t4&1) + 16 jj + j] with a 64-float
   row, so for fixed (j, jj) the 32 lanes hit offsets hl*512 + g*64 + 32 (t4&1) == 0 mod 32: a 32-way conflict on each of
   32 stores per lane (L46: 'wts' 762 ns at Sd1). Rows now have 66 floats and the upper half sits one float later
   (index d + (d >> 5)): lane banks 16 hl + 2 g + (t4&1) are all distinct; readers use the same index.
2. the new token's cache slot cache_loc[b] is loaded at entry (warp 0) with the other seqlens-independent loads; UD4
   loaded it after the new row's math, a dependent DRAM trip on the CTA holding the token (L46: fold 1424 vs 768 ns
   median), which every CTA then waits for at the cluster barrier.
3. 16-byte pushes: each thread forms 4 consecutive outputs of one row (all its smem reads first) and issues one
   st.shared::cluster.v4.f32 per 4 outputs (UD4: one scalar remote store per output).
Host: ud5(... as ud4c ...), ud5_setup(), ud5_attrs(warps, stages, cs, grid_y).
Run: .venv/bin/python attention/local/make_ud5.py [--check]"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "cuda_ud5.py")


def sub1(src, old, new, what, count=1):
    n = src.count(old)
    assert n == count, f"{what}: anchor x{n} (want {count}): {old[:90]!r}"
    return src.replace(old, new)


PUSH_OLD = """  for (int idx = threadIdx.x; idx < 16 * 64; idx += WARPS * 32) {
    const int hr = idx >> 6, d = idx & 63, h = hr >> 3, row = hr & 7;
    float o = 0.f;
#pragma unroll
    for (int w = 0; w < WARPS; ++w) o += sm_w[hr * WARPS + w] * sm_o[w][h][row][d];
    st_cluster(map_rank(slot0 + (hr * LBP + d) * 4, static_cast<uint32_t>(hr % CS)), o);
  }
"""
PUSH_NEW = """  for (int q = threadIdx.x; q < 16 * 16; q += WARPS * 32) {   // UD5: 4 outputs (one 16 B remote store) per step
    const int hr = q >> 4, d4 = 4 * (q & 15), h = hr >> 3, row = hr & 7;
    const int dp = d4 + (d4 >> 5);                    // UD5: padded column (rows of 66, upper half one float later)
    float o4[4] = {0.f, 0.f, 0.f, 0.f};
#pragma unroll
    for (int w = 0; w < WARPS; ++w) {
      const float wt = sm_w[hr * WARPS + w];
#pragma unroll
      for (int e = 0; e < 4; ++e) o4[e] += wt * sm_o[w][h][row][dp + e];
    }
    st_cluster4(map_rank(slot0 + (hr * LBP + d4) * 4, static_cast<uint32_t>(hr % CS)), o4[0], o4[1], o4[2], o4[3]);
  }
"""


def render(variants=None, multirow=False):
    sys.path.insert(0, HERE)
    import make_ud4c
    text = make_ud4c.render(variants, multirow)
    for pat, rep in ((r"\bokc_ud4c", "okc_ud5"), (r"\bOKC_UD4C_", "OKC_UD5_"), (r"\bud4c\(", "ud5("), (r"\bud4c_setup\b", "ud5_setup"),
                     (r"\bud4c_attrs\b", "ud5_attrs"), (r"\bud4c_kernel\b", "ud5_kernel"), (r"\bCUDA_UD4C_", "CUDA_UD5_"),
                     (r"\bUD4C_VARIANTS\b", "UD5_VARIANTS"), (r'"ud4c', '"ud5')):
        text = re.sub(pat, rep, text)
    # 1. padded warp partials
    text = sub1(text, "WARPS * 2 * 8 * 64 * 4", "WARPS * 2 * 8 * 66 * 4", "partial size", count=4)
    text = sub1(text, "  auto sm_o = reinterpret_cast<float (*)[2][8][64]>(dsm);\n",
                "  auto sm_o = reinterpret_cast<float (*)[2][8][66]>(dsm);   // UD5: rows of 66 floats (bank-conflict-free stores)\n", "sm_o")
    text = sub1(text, "sm_o[warp][hl][g][32 * (t4 & 1) + 16 * jj + j] =", "sm_o[warp][hl][g][33 * (t4 & 1) + 16 * jj + j] =", "sm_o store")
    # 2. cache_loc at entry
    text = sub1(text, "  uint2 nk_raw, nv_raw;                                 // UD4: the new token's k / v (4 bf16 each)\n",
                "  const long new_slot = warp == 0 ? cache_loc[b] : 0;   // UD5: the new token's cache slot, at entry\n"
                "  uint2 nk_raw, nv_raw;                                 // UD4: the new token's k / v (4 bf16 each)\n", "cache_loc prefetch")
    text = sub1(text, "    const long row = cache_loc[b];\n", "    const long row = new_slot;\n", "cache_loc use")
    # 3. v4 push
    text = sub1(text, PUSH_OLD, PUSH_NEW, "push")
    text = sub1(text, "__device__ __forceinline__ void st_cluster(uint32_t addr, float v) {\n",
                "__device__ __forceinline__ void st_cluster4(uint32_t addr, float a, float b, float c, float d) {\n"
                "  asm volatile(\"st.shared::cluster.v4.f32 [%0], {%1, %2, %3, %4};\" ::\"r\"(addr), \"f\"(a), \"f\"(b), \"f\"(c), \"f\"(d) : \"memory\");\n"
                "}\n"
                "__device__ __forceinline__ void st_cluster(uint32_t addr, float v) {\n", "st_cluster4")
    assert "LBP = 68" in text and "STAGE_BYTES = 2 * CHUNK * PITCH" in text
    i = text.index('"""', 3) + 3
    return ('"""Generated by make_ud5.py from cuda_ud4c.py (do not edit): UD5, UD4 with L46\'s anatomy fixes (see make_ud5.py).\n'
            'Original docstring follows.\n' + text[3:i] + text[i:])


def sim():
    """Banks of the partial stores (UD5 vs UD4) and of the push reads; the push's (row, column) coverage and that each
    output is the weighted sum of the right padded entries. Formulas asserted present in the generated source."""
    src = render()
    for frag in ("sm_o[warp][hl][g][33 * (t4 & 1) + 16 * jj + j]", "reinterpret_cast<float (*)[2][8][66]>(dsm)",
                 "const int hr = q >> 4, d4 = 4 * (q & 15), h = hr >> 3, row = hr & 7;", "const int dp = d4 + (d4 >> 5);",
                 "o4[e] += wt * sm_o[w][h][row][dp + e];", "st_cluster4(map_rank(slot0 + (hr * LBP + d4) * 4, static_cast<uint32_t>(hr % CS))",
                 "for (int q = threadIdx.x; q < 16 * 16; q += WARPS * 32)"):
        assert src.count(frag) == 1, frag

    def store_off(P, Q, warp, lane, j, jj):
        g, t4 = lane >> 2, lane & 3
        hl = t4 >> 1
        return ((warp * 2 + hl) * 8 + g) * P + Q * (t4 & 1) + 16 * jj + j

    for j in range(16):
        for jj in range(2):
            banks = {store_off(66, 33, 0, l, j, jj) % 32 for l in range(32)}
            assert len(banks) == 32, ("ud5 store conflict", j, jj, banks)
            banks4 = {store_off(64, 32, 0, l, j, jj) % 32 for l in range(32)}
            assert len(banks4) == 1      # UD4's 32-way conflict, as diagnosed
    # every (warp, hl, g, d) of the logical partial lands at a distinct padded slot, d = 32 (t4&1) + 16 jj + j
    seen = {}
    for warp in range(8):
        for lane in range(32):
            g, t4 = lane >> 2, lane & 3
            for j in range(16):
                for jj in range(2):
                    d = 32 * (t4 & 1) + 16 * jj + j
                    off = store_off(66, 33, warp, lane, j, jj)
                    hl = t4 >> 1
                    assert off == ((warp * 2 + hl) * 8 + g) * 66 + d + (d >> 5), (off, d)
                    assert off not in seen
                    seen[off] = (warp, hl, g, d)
                    assert d + (d >> 5) < 66
    # push: threads q cover every (hr, d) once; reads use the same padded index
    for warps in (4, 8):
        cover = {}
        for tid in range(warps * 32):
            for q in range(tid, 256, warps * 32):
                hr, d4 = q >> 4, 4 * (q & 15)
                dp = d4 + (d4 >> 5)
                for e in range(4):
                    assert dp + e == (d4 + e) + ((d4 + e) >> 5)
                    cover[(hr, d4 + e)] = cover.get((hr, d4 + e), 0) + 1
        assert len(cover) == 16 * 64 and set(cover.values()) == {1}
        # read banks per warp per e: conflict-free
        for wq in range(0, 256, 32):
            for e in range(4):
                banks = set()
                for q in range(wq, wq + 32):
                    hr, d4 = q >> 4, 4 * (q & 15)
                    h, row = hr >> 3, hr & 7
                    banks.add(((0 * 2 + h) * 8 + row) * 66 + d4 + (d4 >> 5) + e)
                assert len({b % 32 for b in banks}) == 32
    return True


if __name__ == "__main__":
    sim()
    text = render()
    if "--check" in sys.argv:
        same = os.path.exists(OUT) and open(OUT).read() == text
        print("cuda_ud5.py up to date" if same else "cuda_ud5.py STALE")
        sys.exit(0 if same else 1)
    open(OUT, "w").write(text)
    print(f"wrote {OUT} (bank / coverage model ok)")
