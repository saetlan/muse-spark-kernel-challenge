"""Generates whole-row copier variants (AF56) of the wgmma verify kernels: cuda_w3b.py (from cuda_w3.py), cuda_uw2b.py
(from cuda_uw2.py), cuda_w1nb.py (from cuda_w1n.py). The only code change: the copier's lane -> (key, 16 B chunk) map.
W1 / W2 / W3 / UW2 / W1-N use key 8*(it>>1) + (lane&7), chunk 4*(it&1) + (lane>>3): one warp instruction reads 64 B of
each of 8 random rows (half rows; AF13: ~1.7-2.1 TB/s). The b variants use key 4*it + (lane>>3), chunk lane&7 (W3b:
key 32*cw_ + 4*i2 + (lane>>3)): one instruction reads whole 128 B rows of 4 keys (AF13 / AF19: 3.4-3.8 TB/s).
The shared-memory destinations are the same formulas of (key, chunk), so the tiles' contents are unchanged; this file
asserts that every (key, chunk) of a stage is copied exactly once per pattern and that each key's row comes from the
shuffle lane holding its page entry. Every other byte is the source's, with names suffixed (namespace, host functions,
macros, Python variables) so the b kernels can sit in one module next to the originals.
Run: .venv/bin/python attention/local/make_wholerow.py [--check]"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OLD1 = "        const int key = 8 * (it >> 1) + (lane & 7), ch = 4 * (it & 1) + (lane >> 3);\n"
NEW1 = "        const int key = 4 * it + (lane >> 3), ch = lane & 7;   // whole 128 B rows of 4 keys per instruction (AF56)\n"
OLD3 = ("        const int it = 8 * cw_ + i2;                    // W2c's iterations 8 cw_ .. 8 cw_ + 7: keys 32 cw_ + (0 .. 31)\n"
        "        const int key = 8 * (it >> 1) + (lane & 7), ch = 4 * (it & 1) + (lane >> 3);\n")
NEW3 = "        const int key = 32 * cw_ + 4 * i2 + (lane >> 3), ch = lane & 7;   // whole 128 B rows of 4 keys per instruction (AF56)\n"

SPECS = [  # source, output, (python var prefix old, new), token renames (regex, replacement)
    ("cuda_w3.py", "cuda_w3b.py", ("CUDA_W3_", "CUDA_W3B_"), ("W3_VARIANTS", "W3B_VARIANTS"),
     [(r"\bokc_w3", "okc_w3b"), (r"\bOKC_W3_", "OKC_W3B_"), (r"\battend_w3", "attend_w3b")], OLD3, NEW3),
    ("cuda_uw2.py", "cuda_uw2b.py", ("CUDA_UW2_", "CUDA_UW2B_"), None,
     [(r"\bokc_uw2", "okc_uw2b"), (r"\bOKC_UW2_", "OKC_UW2B_"), (r"\buw2\(", "uw2b("), (r"\buw2_setup\b", "uw2b_setup"),
      (r"\buw2_attrs\b", "uw2b_attrs"), (r"\buw2_kernel\b", "uw2b_kernel")], OLD1, NEW1),
    ("cuda_w1n.py", "cuda_w1nb.py", ("CUDA_W1N_", "CUDA_W1NB_"), None,
     [(r"\bokc_w1n", "okc_w1nb"), (r"\bOKC_W1N_", "OKC_W1NB_"), (r"\battend_w1n", "attend_w1nb")], OLD1, NEW1),
]


def coverage():
    """Old and new maps cover each (key, chunk) of a 64-key stage once; rows come from the entry-holding lane."""
    for pattern in ("old", "new"):
        seen = {}
        for it in range(16):
            for lane in range(32):
                if pattern == "old":
                    key, ch = 8 * (it >> 1) + (lane & 7), 4 * (it & 1) + (lane >> 3)
                else:
                    key, ch = 4 * it + (lane >> 3), lane & 7
                    assert len({4 * it + (ln >> 3) >= 32 for ln in range(32)}) == 1   # one of r0 / r1 per instruction
                seen[(key, ch)] = seen.get((key, ch), 0) + 1
        assert sorted(seen) == [(k, c) for k in range(64) for c in range(8)] and set(seen.values()) == {1}, pattern
    for cw in range(2):   # W3b: copier cw covers keys 32 cw .. +31, each chunk once; shuffle source = key & 31
        seen = {}
        for i2 in range(8):
            for lane in range(32):
                key, ch = 32 * cw + 4 * i2 + (lane >> 3), lane & 7
                assert key >> 5 == cw and 0 <= (key & 31) < 32
                seen[(key, ch)] = seen.get((key, ch), 0) + 1
        assert sorted(seen) == [(k, c) for k in range(32 * cw, 32 * cw + 32) for c in range(8)] and set(seen.values()) == {1}
    for i2 in range(8):   # per instruction: 4 whole rows (8 lanes x 16 B each, consecutive chunks)
        rows = {}
        for lane in range(32):
            rows.setdefault(4 * i2 + (lane >> 3), []).append(lane & 7)
        assert len(rows) == 4 and all(sorted(v) == list(range(8)) for v in rows.values())


def render(spec):
    src_name, out_name, (vo, vn), extra, renames, old, new = spec
    text = open(os.path.join(HERE, src_name)).read()
    assert text.count(old) == 1, (src_name, text.count(old))
    text = text.replace(old, new)
    for pat, rep in renames:
        text = re.sub(pat, rep, text)
    text = text.replace(vo, vn)
    if extra:
        text = text.replace(extra[0], extra[1])
    i = text.index('"""', 3) + 3
    return (f'"""Generated by make_wholerow.py from {src_name} (do not edit): the whole-row copier variant (AF56).\n'
            f'Original docstring follows.\n' + text[3:i] + text[i:])


def main():
    coverage()
    stale = 0
    for spec in SPECS:
        out = os.path.join(HERE, spec[1])
        text = render(spec)
        if "--check" in sys.argv:
            same = os.path.exists(out) and open(out).read() == text
            print(f"{spec[1]} {'up to date' if same else 'STALE'}")
            stale += not same
        else:
            open(out, "w").write(text)
            print(f"wrote {out}")
    sys.exit(1 if stale else 0)


if __name__ == "__main__":
    main()
