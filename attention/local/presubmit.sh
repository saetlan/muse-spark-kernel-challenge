#!/bin/sh
# Local checks before any okc check or submit on muse_attention_decode.
# Usage: sh attention/local/presubmit.sh attention/<file>.py [more]
set -e
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
PY="$ROOT/.venv/bin/python"
for f in "$@"; do
  head -1 "$f" | grep -q "^# okc: problem=muse_attention_decode$" || { echo "missing problem header: $f"; exit 1; }
done
"$PY" "$ROOT/moe/local/lint_submission.py" "$@"
"$PY" -m py_compile "$@"
"$PY" "$ROOT/attention/local/emulate.py" --quick > /dev/null || { echo "emulate failed"; exit 1; }
"$PY" "$ROOT/attention/local/check_dispatch.py" > /dev/null || { echo "check_dispatch failed"; exit 1; }
"$PY" "$ROOT/attention/local/mutation_test.py" > /dev/null || { echo "mutation_test failed"; exit 1; }
# CUDA sources (attention/local/cuda_*.py): register-array indexing, clang syntax, quick emulators
"$PY" "$ROOT/attention/local/check_cuda_registers.py" > /dev/null || { echo "check_cuda_registers failed"; exit 1; }
for spec in cuda_dec2.py:CUDA_DEC2_SRC cuda_dec3.py:CUDA_DEC3_SRC cuda_fused.py:CUDA_FUSED_SRC cuda_ver.py:CUDA_VER_SRC \
            cuda_unified.py:CUDA_UD_SRC cuda_ver2.py:CUDA_VER2_SRC cuda_dec4.py:CUDA_DEC4_SRC cuda_unified2.py:CUDA_UD2_SRC \
            cuda_dec3p.py:CUDA_DEC3P_SRC cuda_dec4p.py:CUDA_DEC4P_SRC cuda_ver3.py:CUDA_VER3_SRC; do
  "$PY" "$ROOT/attention/local/check_cuda_syntax.py" "$ROOT/attention/local/${spec%%:*}" "${spec##*:}" > /dev/null || { echo "clang syntax failed: $spec"; exit 1; }
done
for emu in emulate_cuda_dec2 emulate_cuda_dec3 emulate_cuda_fused emulate_cuda_ver emulate_cuda_ud emulate_cuda_ver2; do
  "$PY" "$ROOT/attention/local/$emu.py" --quick > /dev/null || { echo "$emu failed"; exit 1; }
done
"$PY" "$ROOT/attention/local/sim_ver2_barriers.py" > /dev/null || { echo "sim_ver2_barriers failed"; exit 1; }
# page-table ring (D3/UD2, generated by make_pt_ring.py): files match their generator, protocol sim + its mutants
"$PY" "$ROOT/attention/local/make_pt_ring.py" --check > /dev/null || { echo "cuda_dec4/cuda_unified2 stale vs make_pt_ring.py"; exit 1; }
"$PY" "$ROOT/attention/local/sim_pt_ring.py" > /dev/null || { echo "sim_pt_ring failed"; exit 1; }
"$PY" "$ROOT/attention/local/mutation_test_pt_ring.py" > /dev/null || { echo "mutation_test_pt_ring failed"; exit 1; }
# PDL variants (make_pdl.py): files match their generator; PDL lines are the only differences; no producer
# data touched before griddepcontrol.wait
"$PY" "$ROOT/attention/local/make_pdl.py" --check > /dev/null || { echo "PDL files stale vs make_pdl.py"; exit 1; }
"$PY" "$ROOT/attention/local/check_pdl.py" > /dev/null || { echo "check_pdl failed"; exit 1; }
# S2c (make_s2c.py): file matches its generator; producer page-entry ring protocol
"$PY" "$ROOT/attention/local/make_s2c.py" --check > /dev/null || { echo "cuda_ver3 stale vs make_s2c.py"; exit 1; }
"$PY" "$ROOT/attention/local/sim_ver3_pt.py" > /dev/null || { echo "sim_ver3_pt failed"; exit 1; }
"$PY" "$ROOT/attention/local/sim_ver3_pt.py" cuda_ver4.py:CUDA_VER4_SRC > /dev/null || { echo "sim_ver3_pt failed: cuda_ver4"; exit 1; }
# V4 verify (FP8 consumers): clang, register indexing, register-level emulator through the judge's
# checker (quick set), mutation test of the emulator's cases, v6 glue test (CPU mocks)
"$PY" "$ROOT/attention/local/check_cuda_syntax.py" "$ROOT/attention/local/cuda_ver4.py" CUDA_VER4_SRC > /dev/null || { echo "clang syntax failed: cuda_ver4"; exit 1; }
"$PY" "$ROOT/attention/local/check_cuda_registers.py" cuda_ver4.py:CUDA_VER4_SRC > /dev/null || { echo "check_cuda_registers failed: cuda_ver4"; exit 1; }
"$PY" "$ROOT/attention/local/emulate_cuda_ver4.py" --quick > /dev/null || { echo "emulate_cuda_ver4 failed"; exit 1; }
"$PY" "$ROOT/attention/local/mutation_test_cuda_ver4.py" > /dev/null || { echo "mutation_test_cuda_ver4 failed"; exit 1; }
"$PY" "$ROOT/attention/local/test_v6_glue.py" > /dev/null || { echo "test_v6_glue failed"; exit 1; }
# UD3 (make_ud3.py): file matches its generator, clang, register indexing, ring protocol, push-merge sim
"$PY" "$ROOT/attention/local/make_ud3.py" --check > /dev/null || { echo "cuda_ud3 stale vs make_ud3.py"; exit 1; }
"$PY" "$ROOT/attention/local/check_cuda_syntax.py" "$ROOT/attention/local/cuda_ud3.py" CUDA_UD3_SRC > /dev/null || { echo "clang syntax failed: cuda_ud3"; exit 1; }
"$PY" "$ROOT/attention/local/check_cuda_registers.py" cuda_ud3.py:CUDA_UD3_SRC > /dev/null || { echo "check_cuda_registers failed: cuda_ud3"; exit 1; }
"$PY" "$ROOT/attention/local/sim_pt_ring.py" cuda_ud3.py:CUDA_UD3_SRC > /dev/null || { echo "sim_pt_ring failed: cuda_ud3"; exit 1; }
"$PY" "$ROOT/attention/local/sim_ud3_merge.py" > /dev/null || { echo "sim_ud3_merge failed"; exit 1; }
# UV4 (make_uv4.py): file matches its generator, clang, register indexing, ring protocol (V4's producer),
# barrier/smem protocol, register-level emulator through the judge's checker (quick set), mutation test,
# v7 glue test (CPU mocks)
"$PY" "$ROOT/attention/local/make_uv4.py" --check > /dev/null || { echo "cuda_uv4 stale vs make_uv4.py"; exit 1; }
"$PY" "$ROOT/attention/local/check_cuda_syntax.py" "$ROOT/attention/local/cuda_uv4.py" CUDA_UV4_SRC > /dev/null || { echo "clang syntax failed: cuda_uv4"; exit 1; }
"$PY" "$ROOT/attention/local/check_cuda_registers.py" cuda_uv4.py:CUDA_UV4_SRC > /dev/null || { echo "check_cuda_registers failed: cuda_uv4"; exit 1; }
"$PY" "$ROOT/attention/local/check_uv4_protocol.py" > /dev/null || { echo "check_uv4_protocol failed"; exit 1; }
"$PY" "$ROOT/attention/local/sim_ver3_pt.py" cuda_uv4.py:CUDA_UV4_SRC > /dev/null || { echo "sim_ver3_pt failed: cuda_uv4"; exit 1; }
"$PY" "$ROOT/attention/local/emulate_cuda_uv4.py" --quick > /dev/null || { echo "emulate_cuda_uv4 failed"; exit 1; }
"$PY" "$ROOT/attention/local/mutation_test_cuda_uv4.py" > /dev/null || { echo "mutation_test_cuda_uv4 failed"; exit 1; }
if [ -f "$ROOT/attention/submission_v7_lab.py" ]; then
  "$PY" "$ROOT/attention/local/test_v7_glue.py" > /dev/null || { echo "test_v7_glue failed"; exit 1; }
fi
# V5 (make_ver5.py): file matches its generator, clang, register indexing, producer ring, register-level
# emulator (quick set) and its mutation test; fa3t static check vs the baseline; v7+ glue on the v8 lab base
"$PY" "$ROOT/attention/local/make_ver5.py" --check > /dev/null || { echo "cuda_ver5 stale vs make_ver5.py"; exit 1; }
"$PY" "$ROOT/attention/local/check_cuda_syntax.py" "$ROOT/attention/local/cuda_ver5.py" CUDA_VER5_SRC > /dev/null || { echo "clang syntax failed: cuda_ver5"; exit 1; }
"$PY" "$ROOT/attention/local/check_cuda_registers.py" cuda_ver5.py:CUDA_VER5_SRC > /dev/null || { echo "check_cuda_registers failed: cuda_ver5"; exit 1; }
"$PY" "$ROOT/attention/local/sim_ver3_pt.py" cuda_ver5.py:CUDA_VER5_SRC > /dev/null || { echo "sim_ver3_pt failed: cuda_ver5"; exit 1; }
"$PY" "$ROOT/attention/local/emulate_cuda_ver5.py" --quick > /dev/null || { echo "emulate_cuda_ver5 failed"; exit 1; }
"$PY" "$ROOT/attention/local/mutation_test_cuda_ver5.py" > /dev/null || { echo "mutation_test_cuda_ver5 failed"; exit 1; }
"$PY" "$ROOT/attention/local/check_fa3t.py" > /dev/null || { echo "check_fa3t failed"; exit 1; }
if [ -f "$ROOT/attention/submission_v8_lab.py" ]; then
  "$PY" "$ROOT/attention/local/test_v7_glue.py" "$ROOT/attention/submission_v8_lab.py" > /dev/null || { echo "test_v7_glue (v8 lab) failed"; exit 1; }
fi
# V5t (make_ver5t.py) and the V5 anatomy copy (make_anat5.py): files match their generators, clang, registers,
# producer ring, V5t pipeline protocol sim, V5t emulator + layout mutants
"$PY" "$ROOT/attention/local/make_ver5t.py" --check > /dev/null || { echo "cuda_ver5t stale vs make_ver5t.py"; exit 1; }
"$PY" "$ROOT/attention/local/make_anat5.py" --check > /dev/null || { echo "cuda_anat5 stale vs make_anat5.py"; exit 1; }
for spec in cuda_ver5t.py:CUDA_VER5T_SRC cuda_anat5.py:CUDA_AN5_SRC; do
  "$PY" "$ROOT/attention/local/check_cuda_syntax.py" "$ROOT/attention/local/${spec%%:*}" "${spec##*:}" > /dev/null || { echo "clang syntax failed: $spec"; exit 1; }
  "$PY" "$ROOT/attention/local/check_cuda_registers.py" "$spec" > /dev/null || { echo "check_cuda_registers failed: $spec"; exit 1; }
done
"$PY" "$ROOT/attention/local/sim_ver3_pt.py" cuda_ver5t.py:CUDA_VER5T_SRC > /dev/null || { echo "sim_ver3_pt failed: cuda_ver5t"; exit 1; }
"$PY" "$ROOT/attention/local/sim_ver5t_pipe.py" > /dev/null || { echo "sim_ver5t_pipe failed"; exit 1; }
"$PY" "$ROOT/attention/local/emulate_cuda_ver5t.py" --quick > /dev/null || { echo "emulate_cuda_ver5t failed"; exit 1; }
"$PY" "$ROOT/attention/local/mutation_test_cuda_ver5t.py" > /dev/null || { echo "mutation_test_cuda_ver5t failed"; exit 1; }
# W1 (make_w1.py: wgmma FP8 verify): file matches its generator, clang, registers, static PTX-rule checks
# (descriptor bits, asm form, fence order, barrier counts, SMEM), pipeline protocol sim, emulator through the
# judge's checker (quick set) and its mutation test
"$PY" "$ROOT/attention/local/make_w1.py" --check > /dev/null || { echo "cuda_w1 stale vs make_w1.py"; exit 1; }
"$PY" "$ROOT/attention/local/check_cuda_syntax.py" "$ROOT/attention/local/cuda_w1.py" CUDA_W1_SRC > /dev/null || { echo "clang syntax failed: cuda_w1"; exit 1; }
"$PY" "$ROOT/attention/local/check_cuda_registers.py" cuda_w1.py:CUDA_W1_SRC > /dev/null || { echo "check_cuda_registers failed: cuda_w1"; exit 1; }
"$PY" "$ROOT/attention/local/check_w1_static.py" > /dev/null || { echo "check_w1_static failed"; exit 1; }
"$PY" "$ROOT/attention/local/sim_w1_pipe.py" > /dev/null || { echo "sim_w1_pipe failed"; exit 1; }
"$PY" "$ROOT/attention/local/emulate_cuda_w1.py" --quick > /dev/null || { echo "emulate_cuda_w1 failed"; exit 1; }
"$PY" "$ROOT/attention/local/mutation_test_cuda_w1.py" > /dev/null || { echo "mutation_test_cuda_w1 failed"; exit 1; }
# L15 anatomy copies (make_anatomy.py): file matches its generator; each source parses
"$PY" "$ROOT/attention/local/make_anatomy.py" --check > /dev/null || { echo "cuda_anat stale vs make_anatomy.py"; exit 1; }
for v in CUDA_AN_DEC4_SRC CUDA_AN_UD2_SRC CUDA_AN_VER3_SRC CUDA_AN_MICRO_SRC; do
  "$PY" "$ROOT/attention/local/check_cuda_syntax.py" "$ROOT/attention/local/cuda_anat.py" "$v" > /dev/null || { echo "clang syntax failed: cuda_anat $v"; exit 1; }
done
echo "presubmit: all local checks passed for $*"
