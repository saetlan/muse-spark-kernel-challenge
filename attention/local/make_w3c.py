"""Generates attention/local/cuda_w3c.py: W3c = W3b (cuda_w3b.py: W3 with whole-row copies) at 2 CTAs per SM (AF58).
L32: W3b still moves ~2.3 TB/s on full verify with 2 copier warps and one ring per SM; D3 reaches ~3.1 TB/s with 12
issuing warps per SM. W3c runs 2 consumer warpgroups per CTA (one per KV head, NWG 2) and 2 CTAs per SM:
`__launch_bounds__(384, 2)` caps the launch at 80 registers (pool 384 x 80 = 30,720 per CTA), setmaxnreg moves them to
the consumers (104 / producers 32, or 96 / 48), 3 stages per CTA (2 x 95.5 KB of shared memory). Per SM: 4 consumer
warpgroups, 4 copier warps, 2 rings, 6 stages in flight. Only text changes vs cuda_w3b.py: names (w3b -> w3c), the
launch bounds' min-blocks 1 -> 2, the variant list. Splits: whole waves at 2 CTAs per SM (_nsplit_w(..., 2, 64)).
Run: .venv/bin/python attention/local/make_w3c.py [--check]"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "cuda_w3c.py")
VARIANTS = [(3, 1, 2, 104, 32), (3, 0, 2, 104, 32), (3, 1, 2, 96, 48)]


def render():
    text = open(os.path.join(HERE, "cuda_w3b.py")).read()
    for pat, rep in ((r"\bokc_w3b", "okc_w3c"), (r"\bOKC_W3B_", "OKC_W3C_"), (r"\battend_w3b", "attend_w3c"),
                     (r"\bCUDA_W3B_", "CUDA_W3C_"), (r"\bW3B_VARIANTS", "W3C_VARIANTS")):
        text = re.sub(pat, rep, text)
    old = "__launch_bounds__(128 * NWG + 128, 1) attend_w3c_kernel("
    assert text.count(old) == 1
    text = text.replace(old, "__launch_bounds__(128 * NWG + 128, 2) attend_w3c_kernel(")
    m = re.findall(r"#define OKC_W3C_VARIANTS\(X\) [^\n]*\n", text)
    assert len(m) == 1
    text = text.replace(m[0], "#define OKC_W3C_VARIANTS(X) " + " ".join(f"X({s}, {p}, {n}, {rc}, {rp})" for s, p, n, rc, rp in VARIANTS) + "\n")
    m = re.findall(r"\nW3C_VARIANTS = [^\n]*\n", text)
    assert len(m) == 1
    text = text.replace(m[0], "\nW3C_VARIANTS = " + repr(VARIANTS) + "\n")
    for s, p, n, rc, rp in VARIANTS:   # 2 CTAs per SM: shared memory and register pool
        smem = s * (2 * 4096 + 64 * 144 + 2 * 8 * 528) + 2 * s * 64 * 4 + 2 * n * 4096
        assert 2 * (smem + 1024 + 256) <= 228 * 1024, (s, smem)
        threads = 128 * n + 128
        cap = 0
        for r in range(255, 0, -1):     # largest per-thread count whose per-warp allocation fits 2 CTAs in 64K registers
            if 2 * (threads // 32) * ((r * 32 + 255) // 256 * 256) <= 65536:
                cap = r
                break
        assert threads * cap >= 128 * n * rc + 128 * rp and rp <= cap <= rc, (s, rc, rp, cap)
    i = text.index('"""', 3) + 3
    return ('"""Generated by make_w3c.py from cuda_w3b.py (do not edit): W3c, W3b at 2 CTAs per SM (see make_w3c.py).\n'
            'Original docstring follows.\n' + text[3:i] + text[i:])


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        same = os.path.exists(OUT) and open(OUT).read() == text
        print("cuda_w3c.py up to date" if same else "cuda_w3c.py STALE")
        sys.exit(0 if same else 1)
    open(OUT, "w").write(text)
    print(f"wrote {OUT}")
