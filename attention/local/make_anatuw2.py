"""Generates attention/local/cuda_anatuw2.py: UW2 (cuda_uw2.py, the Sv1 / Sv16 kernel) with L15-style anatomy stamps
(make_anatomy.py's helpers, entry stamp and extra argument), to split a sliding verify call into phases as L33 did for
UD3 (AF59) before reworking it. Each change sits at an anchor that must occur exactly once (asserted). Thread 0
(consumer warp 0) of every CTA stores, in 32 u64 slots per CTA: 0 %globaltimer at entry, 1 %clock64 at entry,
2 seqlens-independent loads issued, 3 RoPE table ready (consumer barrier), 4 query fold stored, 5 the block's new rows
written (consumer barrier), 6 stage 0's K / Vt full (copier + transposers), 7 the consumer loop done, 8 push stores
issued, 9 after the cluster barrier, 13 stages of the slice, 28 %clock64 and 29 %globaltimer at exit (after the
owner's finalize), 30 SM id.
Run: .venv/bin/python attention/local/make_anatuw2.py [--check]"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from make_anatomy import common, load, sub1  # noqa: E402

OUT = os.path.join(HERE, "cuda_anatuw2.py")


def make_uw2():
    src, decl = load("cuda_uw2.py", "CUDA_UW2_SRC")
    src = src.replace("okc_uw2_smem", "okc_an_uw2_smem")   # host helper outside the namespace
    src, decl = common(src, decl, "okc_uw2", "uw2", "an_uw2",
                       "    int hq, int hkv, int max_pages, int page, int window, int rope, float qk_factor, float sm_scale) {",
                       "static_cast<float>(qk_factor), static_cast<float>(sm_scale)",
                       "int64_t rope, double qk_factor, double sm_scale, int64_t stages, int64_t pp, int64_t cs) {",
                       "double sm_scale, int64_t stages, int64_t pp, int64_t cs);")
    src = sub1(src, "    // ---- 2. RoPE table: entry e", "    AN_PUT(2, an_clk_m());\n    AN_PUT(13, nst);\n    // ---- 2. RoPE table: entry e", "loads")
    src = sub1(src, "    asm volatile(\"bar.sync 5, %0;\" ::\"n\"(WC * 32) : \"memory\");   // consumers only: the table is ready\n",
               "    asm volatile(\"bar.sync 5, %0;\" ::\"n\"(WC * 32) : \"memory\");   // consumers only: the table is ready\n"
               "    AN_PUT(3, an_clk_m());\n", "rope")
    src = sub1(src, "    // ---- 4. the block's keys/values held by this CTA", "    AN_PUT(4, an_clk_m());\n    // ---- 4. the block's keys/values held by this CTA", "fold")
    src = sub1(src, "    asm volatile(\"bar.sync 5, %0;\" ::\"n\"(WC * 32) : \"memory\");   // new_k / new_v visible to every consumer\n",
               "    asm volatile(\"bar.sync 5, %0;\" ::\"n\"(WC * 32) : \"memory\");   // new_k / new_v visible to every consumer\n"
               "    AN_PUT(5, an_clk_m());\n", "new rows")
    src = sub1(src, "      wait_full(0);\n      turn_wait();\n      issue_qk(s0, 0);\n",
               "      wait_full(0);\n      AN_PUT(6, an_clk_m());\n      turn_wait();\n      issue_qk(s0, 0);\n", "first full")
    src = sub1(src, "    asm volatile(\"cp.async.wait_all;\");               // this thread's gate pieces landed (read after cluster_sync)\n",
               "    AN_PUT(7, an_clk_m());\n"
               "    asm volatile(\"cp.async.wait_all;\");               // this thread's gate pieces landed (read after cluster_sync)\n", "loop end")
    src = sub1(src, "  cluster_sync();                                     // every row's CS partials in its owner's buffer\n",
               "  AN_PUT(8, an_clk_m());\n"
               "  cluster_sync();                                     // every row's CS partials in its owner's buffer\n"
               "  AN_PUT(9, an_clk_m());\n", "push / cluster barrier")
    src = sub1(src, "    op[32 + lane] = f2bf16(o1 * rn / (1.f + __expf(-gt1)));\n  }\n}\n",
               "    op[32 + lane] = f2bf16(o1 * rn / (1.f + __expf(-gt1)));\n  }\n  AN_END();\n}\n", "end")
    return src, decl


def render():
    src, decl = make_uw2()
    return ('"""Generated by make_anatuw2.py (do not edit): UW2 with anatomy stamps; see make_anatuw2.py for the slots."""\n'
            f"\nCUDA_AN_UW2_SRC = r\"\"\"{src}\"\"\"\n\nCUDA_AN_UW2_DECL = {decl!r}\n")


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        same = os.path.exists(OUT) and open(OUT).read() == text
        print("cuda_anatuw2.py up to date" if same else "cuda_anatuw2.py STALE")
        sys.exit(0 if same else 1)
    open(OUT, "w").write(text)
    print(f"wrote {OUT} ({len(text)} bytes)")
