"""Generates attention/local/cuda_anatud3.py: UD3 (cuda_ud3.py, the Sd1 / Sd16 kernel) with L15-style anatomy stamps
(make_anatomy.py's helpers, entry stamp and extra argument), to split UD3's ~13.7 us raw Sd1 call (L31: ~5 us above the
bare one-launch chain, AF57) into phases before rebuilding the sliding kernels (A65).
Each change sits at an anchor that must occur exactly once (asserted). Thread 0 (warp 0) of every CTA stores, in
32 u64 slots per CTA: 0 %globaltimer at entry, 1 %clock64 at entry, 2 seqlens arrived (clock after a store of n),
3 page entries landed, 4 RoPE table done (before the page-entry wait), 5 query fold done (after a store of qa[7][0]),
6 warp 0's first K/V chunk landed, 7 warp 0's loop end, 8 warp 0's accumulated K/V wait clocks, 9 warps' partials in
smem (after the CTA barrier), 10 CTA weights done (before the push), 11 after the push's cluster barrier,
13 warp 0's chunk count, 28 %clock64 and 29 %globaltimer at exit (non-leaders after slot 11, the leader after its
finalize and stores), 30 SM id.
Run: .venv/bin/python attention/local/make_anatud3.py [--check]"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from make_anatomy import LOOP_WAIT, MERGE_SYNC, common, load, sub1  # noqa: E402

OUT = os.path.join(HERE, "cuda_anatud3.py")


def make_ud3():
    src, decl = load("cuda_ud3.py", "CUDA_UD3_SRC")
    src, decl = common(src, decl, "okc_ud3", "ud3", "an_ud3",
                       "    int hq, int hkv, int max_pages, int nsplit, int page, int window, int rope, float qk_factor, float sm_scale) {",
                       "static_cast<int>(rope), static_cast<float>(qk_factor), static_cast<float>(sm_scale)",
                       "int64_t rope, double qk_factor, double sm_scale, int64_t warps, int64_t stages, int64_t cs) {",
                       "double sm_scale, int64_t warps, int64_t stages, int64_t cs);")
    src = sub1(src, "  // ---- 2. the slice; page entries\n", "  AN_DEP(2, n);\n  // ---- 2. the slice; page entries\n", "seqlens")
    src = sub1(src, "    __syncthreads();\n  }\n\n  // ---- 4. page entries landed",
               "    __syncthreads();\n  }\n  AN_PUT(4, an_clk_m());\n\n  // ---- 4. page entries landed", "rope")
    src = sub1(src, "  // ---- 4. page entries landed: the first STAGES - 1 stages of K/V rows\n"
                    "  asm volatile(\"cp.async.wait_group 0;\");\n  __syncwarp();\n",
               "  // ---- 4. page entries landed: the first STAGES - 1 stages of K/V rows\n"
               "  asm volatile(\"cp.async.wait_group 0;\");\n  __syncwarp();\n  AN_PUT(3, an_clk_m());\n  AN_PUT(13, mine);\n",
               "page entries")
    src = sub1(src, "  if (has_new) __syncthreads();                               // new_k / new_v visible to every warp\n",
               "  if (has_new) __syncthreads();                               // new_k / new_v visible to every warp\n"
               "  AN_DEP(5, qa[7][0]);\n", "fold")
    src = sub1(src, LOOP_WAIT,
               "  unsigned long long an_wacc = 0;\n" + LOOP_WAIT.replace(
                   "    asm volatile(\"cp.async.wait_group %0;\"", "    const unsigned long long an_w0 = an_clk();\n"
                   "    asm volatile(\"cp.async.wait_group %0;\"")
               + "    const unsigned long long an_w1 = an_clk();\n    an_wacc += an_w1 - an_w0;\n"
                 "    if (i == 0) AN_PUT(6, an_w1);\n", "loop wait")
    src = sub1(src, "  asm volatile(\"cp.async.wait_all;\");\n  __syncthreads();                     // every warp",
               "  AN_PUT(7, an_clk_m());\n  AN_PUT(8, an_wacc);\n"
               "  asm volatile(\"cp.async.wait_all;\");\n  __syncthreads();                     // every warp", "loop end")
    src = sub1(src, MERGE_SYNC, MERGE_SYNC + "  AN_PUT(9, an_clk_m());\n", "warp merge")
    src = sub1(src, "  // ---- 8. push the partial", "  AN_PUT(10, an_clk_m());\n  // ---- 8. push the partial", "weights")
    src = sub1(src, "  cluster_sync();                                   // every partial in the leader's buffer\n"
                    "  if (rank != 0) return;\n",
               "  cluster_sync();                                   // every partial in the leader's buffer\n"
               "  AN_PUT(11, an_clk_m());\n  if (rank != 0) { AN_END(); return; }\n", "push barrier")
    src = sub1(src, "    op[32 + lane] = f2bf16(o1 * rn / (1.f + __expf(-gate1[k2])));\n  }\n}\n",
               "    op[32 + lane] = f2bf16(o1 * rn / (1.f + __expf(-gate1[k2])));\n  }\n  AN_END();\n}\n", "leader end")
    return src, decl


def render():
    src, decl = make_ud3()
    return ('"""Generated by make_anatud3.py (do not edit): UD3 with anatomy stamps; see make_anatud3.py for the slots."""\n'
            f"\nCUDA_AN_UD3_SRC = r\"\"\"{src}\"\"\"\n\nCUDA_AN_UD3_DECL = {decl!r}\n")


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        same = os.path.exists(OUT) and open(OUT).read() == text
        print("cuda_anatud3.py up to date" if same else "cuda_anatud3.py STALE")
        sys.exit(0 if same else 1)
    open(OUT, "w").write(text)
    print(f"wrote {OUT} ({len(text)} bytes)")
