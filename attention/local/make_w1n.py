"""Generates attention/local/cuda_w1n.py: W1-N, the L22 debug copy of W1 with its dump switched off by a null
pointer (L23 / AF46: the debug copy is right on every block and split while the plain W1 text is not; the two
differ only in dump code that never runs outside block 0, so the fault is codegen-dependent). W1-N keeps that
exact text (make_w1dbg.py's kernel, built from the W1 of L20-L23) and adds `dbg != nullptr` to the dump guards;
the host passes nullptr. A fallback in case the sync-asm W1 (make_w1.py after L23) is not right either.
Host: attend_w1n(q, kc, vc, k_scale, pt, seqlens, o_part, m_part, l_part, batch, hq, hkv, max_pages, nsplit, page,
window, sm_scale, stages) with stages 3 / 4 / 6 (Vt stride 528, no writer fence); attend_w1n_setup().
FROZEN: generated once from cuda_w1dbg.py as of L22/L23; do not regenerate after make_w1.py changes.
Run: .venv/bin/python attention/local/make_w1n.py [--check]"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "cuda_w1n.py")
SRC_FILE = os.path.join(HERE, "cuda_w1dbg_l22.py")   # frozen copy of the L22/L23 debug kernel


def load(path, var):
    ns = {}
    exec(compile(open(path).read(), path, "exec"), ns)
    return ns[var]


def render():
    d = load(SRC_FILE, "CUDA_W1DBG_L22_SRC")
    kern = d[:d.index("\nvoid attend_w1dbg(")]
    on = "if (DBG && blockIdx.x == 0 && blockIdx.y == 0 && i == 0)"
    assert kern.count(on) == 4
    kern = kern.replace(on, "if (DBG && dbg != nullptr && blockIdx.x == 0 && blockIdx.y == 0 && i == 0)")
    kern = kern.replace("namespace okc_w1d {", "namespace okc_w1n {").replace("}  // namespace okc_w1d", "}  // namespace okc_w1n")
    assert "okc_w1d" not in kern
    host = r"""
#define OKC_W1N_VARIANTS(X) X(3) X(4) X(6)

void attend_w1n(torch::Tensor q, torch::Tensor kc, torch::Tensor vc, torch::Tensor k_scale,
                torch::Tensor page_table, torch::Tensor seqlens, torch::Tensor o_part, torch::Tensor m_part,
                torch::Tensor l_part, int64_t batch, int64_t hq, int64_t hkv, int64_t max_pages, int64_t nsplit,
                int64_t page, int64_t window, double sm_scale, int64_t stages) {
  auto stream = at::cuda::getCurrentCUDAStream();
  TORCH_CHECK(hq == 8 * hkv && hkv % 2 == 0, "attend_w1n: 8 query heads per KV head, KV heads in pairs");
  dim3 grid(static_cast<unsigned>(nsplit), static_cast<unsigned>(batch * (hkv / 2)));
  const size_t smem = static_cast<size_t>(stages) * (okc_w1n::OFF_VT + 2 * 8 * 528) + static_cast<size_t>(2 * stages) * 64 * 4;
  bool launched = false;
#define OKC_W1N_LAUNCH(S)                                                                                         \
  if (!launched && stages == S) {                                                                                 \
    okc_w1n::attend_w1_kernel<S, 528, 0, 1><<<grid, 352, smem, stream>>>(                                         \
        reinterpret_cast<const uint16_t*>(q.data_ptr()), reinterpret_cast<const uint8_t*>(kc.data_ptr()),         \
        reinterpret_cast<const uint8_t*>(vc.data_ptr()), k_scale.data_ptr<float>(), page_table.data_ptr<int>(),  \
        seqlens.data_ptr<int>(), o_part.data_ptr<float>(), m_part.data_ptr<float>(), l_part.data_ptr<float>(),  \
        nullptr, static_cast<int>(hq), static_cast<int>(hkv), static_cast<int>(max_pages),                       \
        static_cast<int>(nsplit), static_cast<int>(page), static_cast<int>(window), static_cast<float>(sm_scale)); \
    launched = true;                                                                                              \
  }
  OKC_W1N_VARIANTS(OKC_W1N_LAUNCH)
#undef OKC_W1N_LAUNCH
  TORCH_CHECK(launched, "attend_w1n: no variant stages=", stages);
  const cudaError_t e = cudaGetLastError();
  TORCH_CHECK(e == cudaSuccess, "attend_w1n launch failed: ", cudaGetErrorString(e));
}

int64_t attend_w1n_setup() {   // once, outside any capture
  int err = 0;
#define OKC_W1N_SMEM(S) \
  err |= cudaFuncSetAttribute(okc_w1n::attend_w1_kernel<S, 528, 0, 1>, cudaFuncAttributeMaxDynamicSharedMemorySize, S * (okc_w1n::OFF_VT + 2 * 8 * 528) + 2 * S * 64 * 4);
  OKC_W1N_VARIANTS(OKC_W1N_SMEM)
#undef OKC_W1N_SMEM
  (void)cudaGetLastError();
  return err;
}
"""
    decl = ("void attend_w1n(torch::Tensor q, torch::Tensor kc, torch::Tensor vc, torch::Tensor k_scale, "
            "torch::Tensor page_table, torch::Tensor seqlens, torch::Tensor o_part, torch::Tensor m_part, "
            "torch::Tensor l_part, int64_t batch, int64_t hq, int64_t hkv, int64_t max_pages, int64_t nsplit, "
            "int64_t page, int64_t window, double sm_scale, int64_t stages);\nint64_t attend_w1n_setup();")
    return ('"""Generated by make_w1n.py (do not edit): W1-N, the L22 debug-layout W1 with the dump off (see make_w1n.py)."""\n\n'
            f"CUDA_W1N_SRC = r\"\"\"\n{kern + host}\"\"\"\n\nCUDA_W1N_DECL = {decl!r}\n")


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        same = os.path.exists(OUT) and open(OUT).read() == text
        print("cuda_w1n.py up to date" if same else "cuda_w1n.py STALE")
        sys.exit(0 if same else 1)
    open(OUT, "w").write(text)
    print(f"wrote {OUT} ({len(text)} bytes)")
