"""Generates attention/local/cuda_ud9.py: UD9 = UD8 (make_ud8.render) with a compact receive buffer: [CS][ROWS][LBP] (each
CTA receives only the 16 / CS rows it owns) instead of UD4's leader layout [CS][16][LBP] in every CTA. Shared memory per
CTA drops by (CS - 1) x 16 x 272 B (cs8: 34.8 -> 4.4 KB, so cs8 w4 s3 fits 3 CTAs per SM). L47 / L49: at Sd32, cs8 w4 s3
had 30 active clusters for the 32 needed (a second wave), so v15 runs cs4 = 1 CTA (4 warps) per SM, and L57 shows Sd16 /
Sd32 bound by the per-warp loop. With the compact buffer cs8 (Sd32: 256 CTAs, 2 per SM) and cs16 (Sd16: 256 CTAs) can run
in one wave with twice the warps per SM. Push: row hr goes to owner hr % CS at local row hr / CS of slot rank; m / l of
row tid likewise; owners read (src, orow).
Host: ud9(... as ud8 ...), ud9_setup(), ud9_attrs(warps, stages, cs, grid_y).
Run: .venv/bin/python attention/local/make_ud9.py [--check]"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import make_ud8  # noqa: E402

OUT = os.path.join(HERE, "cuda_ud9.py")
VARIANTS = [(4, 3, 16), (4, 3, 8), (4, 3, 4), (4, 2, 8), (4, 2, 16)]
sub1 = make_ud8.sub1


def render(variants=None):
    text = make_ud8.render(variants or VARIANTS)
    for old, new in (("okc_ud8", "okc_ud9"), ("OKC_UD8_", "OKC_UD9_"), ("CUDA_UD8_", "CUDA_UD9_"), ("UD8_VARIANTS", "UD9_VARIANTS"),
                     ("ud8(", "ud9("), ("ud8_setup", "ud9_setup"), ("ud8_attrs", "ud9_attrs"), ("ud8_kernel", "ud9_kernel"), ('"ud8', '"ud9')):
        text = text.replace(old, new)
    text = sub1(text, "// leader buffer [CS][16][LBP]", "// UD9: receive buffer [CS][ROWS][LBP] (owned rows only)", "lbuf comment")
    text = sub1(text, "  const uint32_t slot0 = smem_u32(lbuf) + rank * (16 * LBP * 4);   // UD4: slot [rank][hr] in the owner hr % CS's buffer\n",
                "  const uint32_t slot0 = smem_u32(lbuf) + rank * (ROWS * LBP * 4);   // UD9: slot [rank][hr / CS] in the owner hr % CS's buffer\n",
                "slot0")
    text = sub1(text, "st_cluster4(map_rank(slot0 + (hr * LBP + d4) * 4, static_cast<uint32_t>(hr % CS))",
                "st_cluster4(map_rank(slot0 + ((hr / CS) * LBP + d4) * 4, static_cast<uint32_t>(hr % CS))", "push o")
    text = sub1(text, "st_cluster(map_rank(slot0 + (threadIdx.x * LBP + 64) * 4, owner), sm_mm[threadIdx.x]);",
                "st_cluster(map_rank(slot0 + ((threadIdx.x / CS) * LBP + 64) * 4, owner), sm_mm[threadIdx.x]);", "push m")
    text = sub1(text, "st_cluster(map_rank(slot0 + (threadIdx.x * LBP + 65) * 4, owner), sm_lt[threadIdx.x]);",
                "st_cluster(map_rank(slot0 + ((threadIdx.x / CS) * LBP + 65) * 4, owner), sm_lt[threadIdx.x]);", "push l")
    text = sub1(text, "mm = fmaxf(mm, lbuf[(r * 16 + hr) * LBP + 64]);", "mm = fmaxf(mm, lbuf[(r * ROWS + orow) * LBP + 64]);", "read m")
    text = sub1(text, "    const float* pr = lbuf + (r * 16 + hr) * LBP;\n", "    const float* pr = lbuf + (r * ROWS + orow) * LBP;\n", "read o")
    n = text.count("* 16 * okc_ud9::LBP * 4") + text.count("C * 16 * LBP * 4")
    text = text.replace("static_cast<size_t>(cs) * 16 * okc_ud9::LBP * 4", "static_cast<size_t>(16) * okc_ud9::LBP * 4")
    text = text.replace("static_cast<size_t>(C) * 16 * okc_ud9::LBP * 4", "static_cast<size_t>(16) * okc_ud9::LBP * 4")
    text = text.replace("W * S * STAGE_BYTES + C * 16 * LBP * 4", "W * S * STAGE_BYTES + 16 * LBP * 4")
    assert n == 3 and "* 16 * okc_ud9::LBP" not in text.replace("static_cast<size_t>(16) * okc_ud9::LBP", "") and "C * 16 * LBP" not in text, n
    i = text.index('"""', 3) + 3
    return ('"""Generated by make_ud9.py from make_ud8.render (do not edit): UD9, UD8 with a compact receive buffer (see\n'
            'make_ud9.py). Original docstring follows.\n' + text[3:i] + text[i:])


def sim():
    """Every (src rank, owned row) slot is written exactly once (o by the push, m / l by threads tid < 16) inside the
    16-row buffer, and the owner reads exactly the slots written for its rows; formulas asserted present."""
    t = render()
    for frag in ("slot0 + ((hr / CS) * LBP + d4) * 4, static_cast<uint32_t>(hr % CS)", "rank * (ROWS * LBP * 4)",
                 "lbuf[(r * ROWS + orow) * LBP + 64]", "lbuf + (r * ROWS + orow) * LBP",
                 "slot0 + ((threadIdx.x / CS) * LBP + 64) * 4", "const uint32_t owner = static_cast<uint32_t>(threadIdx.x % CS);"):
        assert t.count(frag) == 1, frag
    for w, s, cs in VARIANTS:
        rows = 16 // cs
        written = {}
        for rank in range(cs):
            for hr in range(16):
                owner, local = hr % cs, rank * rows + hr // cs
                assert 0 <= local < 16
                written.setdefault((owner, local), []).append((rank, hr))
        assert all(len(v) == 1 for v in written.values()) and len(written) == 16 * cs
        for owner in range(cs):
            for orow in range(rows):
                hr = owner + cs * orow
                for r in range(cs):
                    assert written[(owner, r * rows + orow)] == [(r, hr)], (cs, owner, orow, r)
        assert w * s * 2 * 16 * 144 + 16 * 68 * 4 <= 227 * 1024
    return True


if __name__ == "__main__":
    sim()
    text = render()
    if "--check" in sys.argv:
        same = os.path.exists(OUT) and open(OUT).read() == text
        print("cuda_ud9.py up to date" if same else "cuda_ud9.py STALE")
        sys.exit(0 if same else 1)
    open(OUT, "w").write(text)
    print(f"wrote {OUT} (slot model ok)")
